"""9 клас, урок ІІ-12. Анімація руху: ключі «Розташування», робочий простір Animation з «Аркушем експозицій»,
ракета злітає (ключі на батьківському об’єкті), камера облітає сцену, рендер відео (Вивід → Відео FFmpeg)."""
from deck import c
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk

L = 12

LAUNCH = K.GROUP_ROCKET + '''
sc = bpy.context.scene
sc.frame_start, sc.frame_end = 1, 96
_r = bpy.data.objects["Ракета"]
for _f, _z in [(1, 0), (24, 0), (96, 14)]:
    _r.location = (0, 0, _z)
    _r.keyframe_insert("location", frame=_f)
_r.rotation_euler = (0, 0, 0); _r.keyframe_insert("rotation_euler", frame=24)
_r.rotation_euler = (0, 0, math.radians(180)); _r.keyframe_insert("rotation_euler", frame=96)
look(bpy.data.objects["Camera"], (12, -12, 5), (0, 0, 4))
'''

P_BOUNCE = K.zrazok(L, "м’яч стрибає", K.BOUNCE, anim=".mp4")
P_LAUNCH = K.zrazok(L, "ракета злітає", LAUNCH, anim=".mp4")
P_ORBIT = K.zrazok(L, "камера облітає будиночок (рівень 3)", K.HOUSE + K.ORBIT_TAIL, anim=".mp4")

SB = K.BOUNCE + 'select("М’яч")\nbpy.context.scene.frame_set(24)\nview(rot=(75, 0, 0), dist=13, target=(0, 0, 1.5))\n'
ANIM = bk(SB, ["mousemove 806 14", "click 1", "sleep 2.5", "mousemove 700 300"],
          parts=[(700, 0, 1366, 30), (0, 535, 900, 712), (1132, 280, 1366, 360)],
          marks=[(777, 5, 836, 25, "right"), (48, 541, 223, 560, "right"), (226, 588, 486, 704, "right"),
                 (1240, 291, 1308, 352, "left")])
SO = K.HOUSE + K.ORBIT_TAIL + 'select("Центр обертання")\nbpy.context.scene.frame_set(30)\n' \
     'view(rot=(64, 0, 35), dist=22, target=(0, 0, 1))\n'
ORBIT = bk(SO, ["mousemove 500 640"], layout="row",
           parts=[(420, 120, 1060, 440), (1132, 56, 1366, 530)],
           marks=[(548, 375, 580, 407, "left"), (968, 138, 1044, 192, "bottom"), (1132, 224, 1366, 243, "left"),
                  (1240, 506, 1308, 526, "left")])
SOUT = K.BOUNCE + 'select("М’яч")\nview(rot=(75, 0, 0), dist=13, target=(0, 0, 1.5))\n'
OUT = bk(SOUT, ["mousemove 1146 374", "click 1", "sleep 1.0", "mousemove 1240 500"] + ["click 5", "sleep 0.1"] * 12 +
         ["sleep 0.5", "mousemove 1300 525", "click 1", "sleep 0.8"],
         parts=[(862, 330, 1366, 740)],
         marks=[(1136, 364, 1158, 386, "left"), (1174, 440, 1350, 461, "top"), (1249, 515, 1350, 536, "top"),
                (1213, 616, 1330, 640, "bottom")])

d = K.deck(L, "", "")

s = d.title("G ◆", "Анімація руху", "М’яч, ракета й камера · 9 клас", big_size=280, big_top=600,
            notes="Минулого разу об’єкти крутилися й «дихали» на місці. Сьогодні вони рухаються сценою: м’яч стрибає, ракета "
                  "злітає, а камера облітає будиночок, як дрон. Наприкінці — справжнє відео MP4.")
K.render_img(s, 1180, 150, 620, P_LAUNCH)

d.plan(["Як стрибає м’яч?", "Рух = ключі «Розташування»", "Робочий простір Animation", "Зроби зараз: м’яч",
        "Ракета злітає", "Камера-дрон", "Відео MP4", "Практика й оцінювання"],
       notes="Повторюємо: кадр → значення → I. Нове: ключі руху, «Аркуш експозицій», камера, рендер відео.")

s = d.slide("Як стрибає м’яч?",
            "Гачок: киньте справжній м’ячик (або згадайте). Питаємо: «Чому кожен наступний стрибок нижчий?» → м’яч втрачає "
            "енергію під час удару. «Де м’яч рухається найшвидше?» → біля землі; найповільніше — нагорі.\n"
            "Аніматори кажуть: щоб рух виглядав живим, треба спостерігати за справжнім. Сьогодні перенесемо це в Blender: "
            "ключі в точках удару (низ) і у верхніх точках.")
s.h2("Як стрибає м’яч?")
K.render_img(s, 128, 220, 1000, P_BOUNCE)
s.card(1180, 220, 612, 280, "Питання", ["Чому кожен стрибок <b>нижчий</b>?", "Де м’яч найшвидший?"], kind="light",
       title_size=34, body_size=31, valign="flex-start")
with s.frame("pop"):
    s.card(1180, 540, 612, 300, "Відповідь", ["Втрачає енергію при ударі.", "Найшвидший — біля землі."], kind="orange",
           title_size=34, body_size=31, valign="flex-start")

s = d.slide("Рух = ключі «Розташування»",
            "Ключі ставимо у важливих точках: старт угорі, удари об землю (Z = 0.5 — радіус м’яча) і верхні точки стрибків, "
            "які щоразу нижчі. X весь час росте — м’яч котиться вперед.\n"
            "Між ключами Blender сам домалює всі кадри.\nПитаємо: «Чому Z на ударі 0.5, а не 0?» → центр м’яча на висоті "
            "радіуса, інакше м’яч «провалиться» в підлогу.")
s.h2("Рух = ключі «Розташування»")
s.table(128, 220, [300, 200, 200, 200, 200, 200, 200], [["Кадр", "1", "16", "32", "48", "60", "72"],
                                                        ["X", "−4", "−2.6", "−1.2", "0.2", "1.4", "2.6"],
                                                        ["Z", "3", "0.5", "2.2", "0.5", "1.4", "0.5"],
                                                        ["Що це", "старт", "удар", "верх", "удар", "верх", "удар"]],
        row_h=92, size=31)
with s.frame("pop"):
    s.note(700, "Z на ударі = <b>0.5</b> — це радіус м’яча (Масштаб 0.5). Інакше м’яч «провалиться».", size=32)

how(d, "Робочий простір Animation",
    "Справжній скрін. 1 — угорі вкладка «Animation»: вікно перебудовується для анімації. 2 — внизу «Аркуш експозицій»: "
    "3 — кожна жовта крапка — ключ (рядки X, Y, Z Розташування). Ключі можна виділити й посунути G — рух стане швидшим "
    "чи повільнішим. 4 — поля «Розташування» зелені: м’яч між ключами.\n"
    "Назад до звичного вигляду — вкладка «Layout».\nТипова хиба: поставили ключ «Обертання» замість «Розташування» — м’яч не рухається.",
    ["Вкладка <b>Animation</b>.", "<b>Аркуш експозицій</b>.", "Крапки — <b>ключі</b>; G — посунути.",
     "Зелені поля — між ключами."], ANIM, side=False, size=28)

s = d.now("Зроби зараз: м’яч стрибає",
          "Новий файл: видаліть куб, додайте Сферу UV, Масштаб 0.5, Згладжене тонування. Числа — на слайді.\n"
          "Зарахувати: 6 ключів «Розташування», кожен стрибок нижчий, м’яч не провалюється в підлогу; Кінець = 72.",
          minutes=10)
s.steps(["Таймлайн: <b>Кінець</b> = " + c("72") + ".",
         "Для кожного кадру з таблиці: <b>Кадр</b> → X і Z у «Розташуванні» → <b>I → Розташування</b>.",
         "Пробіл — дивимось. Збережіть " + c("М’яч — Прізвище.blend") + "."], w=1000, size=29, gap=14)
s.table(128, 560, [180, 130, 130, 130, 130, 130, 130], [["Кадр", "1", "16", "32", "48", "60", "72"],
                                                        ["X", "−4", "−2.6", "−1.2", "0.2", "1.4", "2.6"],
                                                        ["Z", "3", "0.5", "2.2", "0.5", "1.4", "0.5"]], row_h=72, size=28)
K.render_img(s, 1180, 216, 612, P_BOUNCE, label="зразок: м’яч стрибає")

s = d.now("Зроби зараз: ракета злітає",
          "Відкрийте ракету з уроку ІІ-08 (деталі прив’язані!). Ключі ставимо лише на батьківський об’єкт — діти летять самі.\n"
          "Зарахувати: ракета стоїть 1 секунду, потім злітає й повертається навколо осі; деталі не відстають.", minutes=8)
s.steps(["Відкрийте " + c("Ракета — Прізвище.blend") + ". <b>Кінець</b> = " + c("96") + ".",
         "Виділіть <b>батька</b> (Корпус або «Ракета»).",
         "Ключі з таблиці: <b>I → Розташування</b> (і <b>Обертання</b> на кадрах 24 і 96).",
         "Пробіл. Злетіла ціла? Збережіть як " + c("Політ — Прізвище.blend") + "."], w=1000, size=29, gap=14)
s.table(128, 640, [220, 200, 200, 200], [["Кадр", "1", "24", "96"], ["Розташування Z", "0", "0", "14"],
                                         ["Обертання Z", "—", "0°", "180°"]], row_h=66, size=27)
K.render_img(s, 1180, 216, 612, P_LAUNCH, label="зразок: ракета злітає")

how(d, "Камера-дрон",
    "Справжній скрін. Камеру не анімуємо напряму — її «садять» на порожній об’єкт у центрі сцени й крутимо його.\n"
    "1 — порожній «Центр обертання» в центрі (Додати → Порожняк → Прості осі). 2 — камера прив’язана до нього: пунктир "
    "від камери до центру (виділити камеру, потім Shift + клік центр, Ctrl + P → Об’єкт). 3 — у «Структурі» видно обидва. "
    "4 — ключі «Обертання Z»: кадр 1 — 0°, кадр 121 — 360°, інтерполяція «Лінійно».\nПодивитися крізь камеру — цифра 0.",
    ["<b>Порожній</b> у центрі сцени.", "Камера → <b>Ctrl + P</b> до порожнього.", "Обидва в «Структурі».",
     "Ключі <b>Обертання Z</b>: 0° → 360°. Цифра <b>0</b> — вигляд камери."], ORBIT, side=False, size=27)

how(d, "Відео MP4",
    "Справжній скрін вкладки «Вивід» (принтер). Прокрутіть до розділу «Вивід».\n1 — вкладка «Вивід». 2 — шлях: клацніть "
    "папку й оберіть, куди зберегти (за замовчуванням /tmp/ — там не знайдете!). 3 — «Формат файлу» → 4 — «Відео FFmpeg». "
    "Нижче з’явиться «Кодування» → Контейнер MPEG-4.\nПотім меню Рендер → Рендер анімації (Ctrl + F12). Чекаємо: кожен "
    "кадр рендериться окремо.\nПорада: для швидкості в «Формат» поставте 50 %.",
    ["Вкладка <b>Вивід</b>.", "Шлях — <b>своя папка</b>.", "<b>Формат файлу</b>…", "…<b>Відео FFmpeg</b>, MPEG-4. Ctrl + F12."],
    OUT, w_steps=640, size=29)

d.your_turn([("star", "Оберіть свій рівень"), ("book", "Без світла 1: графік стрибка"),
             ("edit", "Без світла 2: план руху ракети"), ("chart", "Як оцінюємо")],
            notes="Домашнє завдання: продумати сценарій для практичної роботи № 7 — 5 секунд, хоча б 2 об’єкти рухаються.")

d.levels([("М’яч стрибає", "до 6 балів", ["6 ключів з таблиці.", "Стрибки нижчають.", "Не провалюється."]),
          ("Ракета злітає", "до 9 балів", ["Ключі на батьку.", "Стоїть 1 с, потім летить.", "Обертається в польоті."]),
          ("Камера-дрон", "до 12 балів", ["Камера на порожньому.", "Лінійний оберт 360°.", "Відео MP4 збережено."])],
         notes="Рівень 3: перевіряємо відео — файл MP4 відкривається, камера рівномірно облітає модель.")

s = d.task("Без світла 1: графік стрибка",
           "Зараховуємо: вісь «кадр» (0–72) і вісь «висота Z»; 6 точок з таблиці з’єднано дугами (не прямими!); точки ударів на "
           "висоті 0.5.\nБали: точки — 2, дуги — 1.", where="У зошиті")
s.steps(["Накресліть осі: <b>кадр</b> (вправо, 1 клітинка = 4 кадри) і <b>Z</b> (вгору, 2 клітинки = 1 м).",
         "Поставте точки з таблиці.", "З’єднайте <b>дугами</b>, як летить м’яч."], w=1100, size=30, gap=16)
s.table(128, 520, [220, 140, 140, 140, 140, 140, 140], [["Кадр", "1", "16", "32", "48", "60", "72"],
                                                        ["Z", "3", "0.5", "2.2", "0.5", "1.4", "0.5"]], row_h=80, size=30)
K.render_img(s, 1290, 216, 502, P_BOUNCE, label="м’яч стрибає")

s = d.task("Без світла 2: план руху ракети",
           "Відповіді: а) 4 с (96 : 24); б) 1 с стоїть; в) на батьківському; г) кадр 60 — Z = 7 (половина шляху, якщо рівномірно).\n"
           "Бали: 4 правильні — 3; 2–3 — 2.", where="У зошиті")
s.steps(["Ключі ракети: кадр 1 — Z 0, кадр 24 — Z 0, кадр 96 — Z 14. Дайте відповіді."], w=1664, size=30)
for k, t in enumerate(["а) Скільки секунд триває анімація?", "б) Скільки ракета стоїть на старті?",
                       "в) На якому об’єкті ставимо ключі: корпус, крило чи батько?", "г) Приблизно де ракета на кадрі 60?"]):
    s.card(128, 300 + k * 125, 1100, 105, None, t, kind="light", body_size=30)
K.render_img(s, 1290, 300, 502, P_LAUNCH)

K.zrazky_slide(d, L)

d.rubric([("Ключі руху", "кадр → Розташування → I", "2"),
          ("Аркуш експозицій", "бачить і посуває ключі", "2"),
          ("Кадри й секунди", "24 кадри = 1 с, Кінець", "2"),
          ("М’яч", "6 ключів, стрибки нижчають", "3"),
          ("Ракета / камера / відео", "ключі на батьку, MP4", "3")], total="12",
         notes="Без світла: графік стрибка — 3, план руху ракети — 3, сценарій ПР 7 — 3, бліц «який ключ ставимо?» — 3.")

K.save(d, L)
