def para(align, n=4, last=.6, indent=0):
    rows = []
    for i in range(n):
        frac = last if i == n - 1 else (1 if align == "justify" else [.92, .8, .97, .86][i % 4])
        al = "left" if align == "justify" else align
        rows.append(("l", frac, al, indent if i == 0 else 0))
    return rows


