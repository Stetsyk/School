def code_task(title, notes, steps, code, where="За комп’ютером", now=None, screen=None, screen_label="ЗРАЗОК",
              code_size=27, steps_w=760, code_h=None, screen_h=200):
    s = d.now(title, notes, minutes=now) if now else d.task(title, notes, where=where)
    s.steps(steps, w=steps_w, size=29, gap=18)
    x = 128 + steps_w + 50
    w = 1792 - x
    lines = code.count("\n") + 1
    h = code_h or min(760, 80 + lines * int(code_size * 1.55))
    s.code(x, 216, w, h, code, size=code_size, framed=False)
    if screen is not None:
        s.screen(x, 216 + h + 24, w, screen_h, screen, label=screen_label)
    return s


def lock(s, x, y, open_=True, label=""):
    col = "#8FC78A" if open_ else "#E8857A"
    tr = 'transform="translate(0,-18)"' if open_ else ""
    s.raw(f'<svg style="position:absolute;left:{x}px;top:{y}px" width="120" height="140" viewBox="0 0 120 140">'
          f'<path d="M30 62 V40 a30 30 0 0 1 60 0 {"V20" if open_ else "V62"}" fill="none" stroke="#3E3F42" stroke-width="10" '
          f'{tr}/>'
          f'<rect x="14" y="60" width="92" height="74" rx="12" fill="{col}" stroke="#3E3F42" stroke-width="4"/></svg>')
    if label:
        s.text(x - 40, y + 146, 200, 40, label, size=24, weight=700, align="center")


