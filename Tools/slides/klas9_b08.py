"""9 клас, урок ІІ-08. Складені моделі: виділення кількох об’єктів, прив’язування Ctrl + P, ієрархія в «Структурі».
Скріни — справжній Blender: кілька виділених деталей ракети, меню «Встановити приріднення до», ієрархія «Ракета»."""
from deck import c
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk

L = 8

STREET = K.HOUSE + '''
for _o in list(bpy.data.objects):
    if _o.type == "MESH":
        for _dx in (-4.5, 4.5):
            _c = _o.copy()
            _c.location.x += _dx
            _c.name = _o.name + (" лівий" if _dx < 0 else " правий")
            bpy.context.collection.objects.link(_c)
look(bpy.data.objects.get("Camera"), (13, -15, 8), (0, 0, 1.2))
'''

P_HOUSE = K.zrazok(L, "будиночок", K.HOUSE)
P_ROCKET = K.zrazok(L, "ракета — деталі прив’язані до «Ракета»", K.GROUP_ROCKET)
P_STREET = K.zrazok(L, "вулиця з трьох будиночків (рівень 2)", STREET)

V = 'view(rot=(66, 0, 35), dist=12, target=(0, 0, 2.2))\n'
SEL = 'select("Ніс", "Ілюмінатор", "Крило 1", "Крило 2", "Крило 3", "Полум’я", "Корпус")\n'
MULTI = bk(K.ROCKET + SEL + V, ["mousemove 500 640"], layout="row",
           parts=[(420, 170, 700, 500), (1132, 56, 1366, 260)],
           marks=[(486, 192, 634, 488, "left"), (1150, 140, 1366, 252, "left")])
CTRLP = bk(K.ROCKET + SEL + V, ["mousemove 600 420", "key ctrl+p", "sleep 0.8"],
           parts=[(330, 170, 700, 550)],
           marks=[(500, 192, 620, 372, "left"), (382, 380, 652, 402, "right"), (386, 408, 648, 428, "right")])
TREEV = bk(K.GROUP_ROCKET + 'select("Ракета")\n' + V, ["mousemove 1182 149", "click 1", "sleep 0.6", "mousemove 500 640"],
           layout="row", parts=[(420, 170, 700, 500), (1132, 56, 1366, 260)],
           marks=[(548, 466, 580, 496, "left"), (1180, 141, 1300, 159, "left"), (1200, 161, 1300, 252, "left")])

d = K.deck(L, "", "")

s = d.title("Ctrl P", "Складені моделі", "Деталі, що рухаються разом · 9 клас", big_size=240, big_top=610,
            notes="Ракета з восьми деталей. Якщо переносити кожну окремо — щось обов’язково «відвалиться». Сьогодні вчимося "
                  "прив’язувати деталі до головної, щоб модель рухалася цілою.")
K.render_img(s, 1180, 150, 620, P_ROCKET)

d.plan(["Ракета розсипалась!", "Виділити кілька: Shift + клік", "Прив’язати: Ctrl + P", "Батько й діти в «Структурі»",
        "Прив’язати чи об’єднати?", "Зроби зараз: ракета", "Зроби зараз: будиночок і вулиця", "Практика й оцінювання"],
       notes="Слова уроку: складена модель, батьківський об’єкт (батько), дочірні об’єкти (діти), ієрархія.")

s = d.slide("Ракета розсипалась!",
            "Гачок: ракета з 8 деталей стоїть на старті. Учень виділяє корпус і піднімає вгору — G, Z. Питаємо: «Що полетить?» "
            "→ лише корпус! Ніс, крила й полум’я лишаться на землі.\n"
            "Висновок: деталі треба «зв’язати». У 3D це називається прив’язування: одна деталь — батько, решта — діти. "
            "Рухаєш батька — діти летять за ним.")
s.h2("Ракета розсипалась!")
K.render_img(s, 128, 220, 820, P_ROCKET, label="ракета: 8 деталей")
s.card(1000, 220, 792, 280, "Питання", ["Виділили <b>корпус</b> і підняли: G, Z, " + c("3") + ".",
                                         "Що полетить угору?"], kind="light", title_size=34, body_size=31, valign="flex-start")
with s.frame("pop"):
    s.card(1000, 540, 792, 300, "Лише корпус!", ["Ніс і крила лишилися на землі.", "Деталі треба <b>прив’язати</b>."],
           kind="orange", title_size=34, body_size=31, valign="flex-start")

