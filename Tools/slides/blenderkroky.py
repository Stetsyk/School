def box(c, side="right", half=13):
    if len(c) == 4:
        return (*c, side)
    x, y = c
    return (x - half, y - half, x + half, y + half, side)


def bfull(setup, xdo=None):
    return bshot(setup, xdo)


def bk(setup, xdo=None, parts=((0, 0, 1366, 768),), marks=(), nums=None, layout=None):
    """Справжній скрін Blender → шматки parts (у точках) → позначки marks (x0, y0, x1, y1, бік) з номерами кроків."""
    png = bshot(setup, xdo)
    src = json.dumps([png, list(parts), list(marks), nums, layout], ensure_ascii=False)
    src += open(os.path.join(HERE, "kroky.py"), encoding="utf-8").read()
    h = hashlib.md5(src.encode()).hexdigest()[:14]
    out = os.path.join(CACHE, f"bkroky-{h}.png")
    if not os.path.exists(out):
        im = Image.open(png).convert("RGB")
        crops = [(tuple(p), im.crop(tuple(v * 2 for v in p))) for p in parts]
        compose(crops, list(marks), nums, layout == "row", out, "blender")
    open(out + ".title", "w").write("Blender")
    return out

