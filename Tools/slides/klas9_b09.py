bm = bmesh.new(); bm.from_mesh(o.data)
top = [f for f in bm.faces if f.normal.z > 0.9]
r = bmesh.ops.extrude_face_region(bm, geom=top)
vs = [e for e in r["geom"] if isinstance(e, bmesh.types.BMVert)]
for v in vs:
    v.co.z += 1.0
    v.co.x = 0.0
    v.co.y = 0.0
