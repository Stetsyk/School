           "Зараховуємо: сидіння й спинка — витягнуті куби (паралелепіпеди), 2–4 ніжки; для кожного примітиву — орієнтовне місце "
           "(вище/нижче, ліворуч/праворуч) або координати.\nБали: список примітивів — 1, розміри — 1, ескіз — 1.",
