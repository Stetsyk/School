"""9 клас, урок ІІ-05. Додавання тривимірних примітивів. Переміщення об’єктів.
Скріни — справжній Blender: інструмент «Перемістити» зі стрілками-осями, поля «Розташування», дублювання."""
from deck import c, INK2, ORANGE, BLUE
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk, box, TOOL, FIELD, FIELD_GROUP, orow, AWAY

L = 5
P_PYR = K.zrazok(L, "пірамідка з шести кубів", K.PYRAMID)
P_STAIRS = K.zrazok(L, "сходи з кубів (рівень 2)", K.STAIRS)
P_BENCH = K.zrazok(L, "лава з примітивів (домашнє завдання)", K.BENCH)

V = 'view(rot=(64, 0, 35), dist=16, target=(0, 0, 2.6))\n'
MOVE = bk(K.PYRAMID + 'select("Куб 6")\n' + V + K.TOOL_MOVE, ["mousemove 700 650"], layout="row",
          parts=[(0, 146, 60, 222), (360, 110, 720, 340), (1170, 388, 1366, 466)],
          marks=[box(TOOL["Перемістити"], "right"), (553, 138, 573, 178, "right"), (1176, 396, 1306, 458, "left")])
FIELDS = bk(K.PYRAMID + 'select("Куб 6")\n' + V, [AWAY], parts=[(1132, 56, 1366, 470)],
            marks=[orow(7, "left"), (1176, 396, 1306, 458, "left"), (1242, 438, 1306, 458, "bottom")])
GKEY = bk(K.PYRAMID + 'select("Куб 6")\n' + V,
          ["mousemove 560 220", "key g", "sleep 0.3", "key z", "mousemove 560 180", "sleep 0.3", "mousemove 560 150",
           "sleep 0.8"], parts=[(0, 28, 1128, 520)], marks=[(0, 30, 760, 54, "bottom")], nums=(None,))
OUTL = bk(K.PYRAMID + 'select("Куб 6")\n' + V, [AWAY], parts=[(1132, 56, 1366, 270)], marks=[orow(7, "left")])

d = K.deck(L, "", "")

s = d.title("G", "Переміщення об’єктів", "Примітиви на своїх місцях · 9 клас", big_size=320, big_top=580,
            notes="Минулого разу примітиви з’являлися в центрі й налазили один на одного. Сьогодні вчимося ставити кожен "
                  "точно туди, куди треба: мишкою, клавішею G і числами.")
K.render_img(s, 1180, 150, 620, P_PYR)

d.plan(["Пірамідка: де кожен кубик?", "Координати X, Y, Z", "Інструмент «Перемістити»", "Клавіша G і осі",
        "Точно — числами", "Хто є хто: «Структура»", "Дублювати: Shift + D", "Практика й оцінювання"],
       notes="Головне вміння — ставити об’єкт числами в полі «Розташування». Мишкою — швидко, числами — точно.")

s = d.slide("Пірамідка: де кожен кубик?",
            "Гачок: рендер пірамідки з шести кубів. Питаємо: «Чим відрізняються кубики?» → нічим, крім місця.\n"
            "Місце об’єкта в 3D — це три числа: X, Y, Z. Знаючи їх, можна поставити кубик точно, без «на око».\n"
            "Стандартний куб має розмір 2 × 2 × 2 м, тому центр нижнього ряду — на висоті Z = 1, а кубики стоять через 2.")
s.h2("Пірамідка: де кожен кубик?")
K.render_img(s, 128, 220, 900, P_PYR)
s.table(1080, 220, [260, 160, 160, 132], [["Кубик", "X", "Y", "Z"], ["нижні", "−2 · 0 · 2", "0", "1"],
                                          ["середні", "−1 · 1", "0", "3"], ["верхній", "0", "0", "5"]],
        row_h=86, size=28)
with s.frame():
    s.note(820, "Куб у Blender: <b>2 × 2 × 2</b> м. Стоїть на підлозі, якщо центр на <b>Z = 1</b>.", size=31)

s = d.slide("Координати X, Y, Z",
            "Повторюємо осі. Червона X — праворуч, зелена Y — вглиб, синя Z — вгору. Точка (0, 0, 0) — центр світу, "
            "де перетинаються червона й зелена лінії на підлозі.\n"
            "Питаємо: «Куб на (0, 0, 1). Куди він переїде, якщо Z = 5?» → підніметься вгору на 4 метри, «зависне» в повітрі.")
s.h2("Координати X, Y, Z")
for k, (a, t, col) in enumerate([("X", "праворуч (+) · ліворуч (−)", "#D9342B"), ("Y", "вглиб (+) · до нас (−)", "#4E8F4A"),
                                 ("Z", "вгору (+) · вниз (−)", "#2F6FB7")]):
    s.text(128, 240 + k * 170, 140, 140, a, size=110, weight=800, color=col)
    s.text(300, 268 + k * 170, 900, 100, t, size=40)
with s.frame("pop"):
    s.card(1250, 240, 542, 470, "Питання",
           ["Куб на <b>(0, 0, 1)</b>.", "Z = <b>5</b> — що станеться?", "", "→ піднявся на 4 м і «завис»."], kind="orange",
           title_size=34, body_size=31, valign="flex-start")

how(d, "Інструмент «Перемістити»",
    "Справжній скрін: 1 — інструмент «Перемістити» на панелі ліворуч (клавіша для інструмента — T не потрібна, просто клацнути). "
    "2 — на виділеному кубі з’являються стрілки: тягнемо синю — тільки вгору-вниз, червону — по X, зелену — по Y. "
    "3 — числа «Розташування» праворуч змінюються самі.\nЗа білий кружечок у центрі — вільно, в площині екрана (так легко "
    "«загубити» об’єкт углиб).",
    ["Інструмент <b>Перемістити</b>.", "Тягніть <b>стрілку</b> потрібного кольору.", "Дивіться, як змінюються числа <b>Розташування</b>."],
    MOVE, w_steps=520, size=30)

s = d.slide("Клавіша G і осі",
            "Справжній скрін під час переміщення клавішею: G (grab — схопити), потім Z — рух лише вздовж осі Z (синя лінія). "
            "Угорі Blender пише, на скільки зсунули. Клацнути ліву кнопку — готово; права кнопка або Esc — скасувати.\n"
            "Можна набрати число: G, Z, 2, Enter — підняти рівно на 2 м.\n"
            "Питаємо: «Як посунути лише вбік, по X, на 3 метри?» → G, X, 3, Enter.")
s.h2("Клавіша G і осі")
s.gshot(128, 210, 1060, GKEY, maxh=520, align="left")
s.card(1230, 210, 562, 520, "G · вісь · число",
       ["<b>G</b> — схопити.", "<b>X</b> / <b>Y</b> / <b>Z</b> — тільки вздовж осі.", "Число, напр. " + c("2") + " → <b>Enter</b>.",
        "Ліва кнопка — готово.", "<b>Esc</b> / права — скасувати."], kind="blue", title_size=34, body_size=29,
       valign="flex-start")
with s.frame():
    s.note(790, "Мишка має бути над <b>3D-вікном</b> — інакше клавіші не працюють.", size=31)

how(d, "Точно — числами",
    "Справжній скрін «Властивостей» (вкладка «Об’єкт», помаранчевий квадратик). 1 — виділений об’єкт видно в «Структурі». "
    "2 — група «Розташування»: X, Y, Z. 3 — двічі клацнути поле Z і набрати 5 → Enter.\n"
    "Лайфхак: клацнути поле й тягнути мишкою вліво-вправо — число плавно змінюється.\n"
    "Типова хиба: учень змінює числа іншого об’єкта — дивіться на назву вгорі «Властивостей».",
    ["Клацніть об’єкт (у сцені або в «Структурі»).", "Знайдіть <b>Розташування</b> X, Y, Z.",
     "Двічі клацніть поле → число → <b>Enter</b>."], FIELDS, w_steps=760, size=31)

s = d.now("Зроби зараз: пірамідка з шести кубів",
          "Кубики додаємо через «Додати → Сіть → Куб» і ставимо числами. Таблиця координат — на цьому слайді.\n"
          "Зарахувати: 6 кубів стоять як на рендері, без проміжків і без налізання; збережено «Пірамідка — Прізвище.blend».",
          minutes=8)
s.steps(["Видаліть стартовий куб. Додайте <b>шість</b> кубів (<b>Додати → Сіть → Куб</b>).",
         "Кожному в <b>Розташуванні</b> задайте X і Z з таблиці (Y = 0).",
         "Перевірте: збоку (клавіша 3) кубики стоять один на одному?",
         "<b>Файл → Зберегти як…</b> " + c("Пірамідка — Прізвище.blend") + "."], w=900, size=29, gap=16)
s.table(128, 650, [300, 200, 200], [["Кубик", "X", "Z"], ["1, 2, 3", "−2 · 0 · 2", "1"], ["4, 5", "−1 · 1", "3"], ["6", "0", "5"]],
        row_h=70, size=27)
K.render_img(s, 1100, 216, 692, P_PYR, label="зразок: пірамідка")

s = d.slide("Хто є хто: «Структура»",
            "Справжній скрін «Структури» (Outliner): усі об’єкти сцени списком. Клацнути назву — виділити об’єкт, навіть якщо він "
            "схований за іншими. Двічі клацнути — перейменувати (наприклад «Сидіння», «Ніжка 1»).\n"
            "Око — сховати об’єкт у вікні, як шар у Krita.\nПитаємо: «Кубик схований усередині іншого. Як його виділити?» → у «Структурі».")
s.h2("Хто є хто: «Структура»")
s.gshot(128, 210, 760, OUTL, maxh=640, align="left")
s.card(950, 210, 842, 600, "«Структура»",
       ["Клацнути назву — <b>виділити</b>.", "Двічі клацнути — <b>перейменувати</b>.", "Око — <b>сховати</b> / показати.",
        "Схований усередині об’єкт — знайдете тут."], kind="blue", title_size=34, body_size=30, valign="flex-start")

s = d.slide("Дублювати: Shift + D",
            "Копія виділеного об’єкта: Shift + D, і копія одразу «прилипає» до мишки — можна натиснути X і число, щоб відсунути "
            "рівно на 2 м: Shift + D, X, 2, Enter. Права кнопка — копія лишиться на місці оригіналу (обережно: дві однакові "
            "в одному місці!).\nТак швидко роблять ряди: ніжки стола, сходинки, стовпці паркану.")
s.h2("Дублювати: Shift + D")
s.steps(["Виділіть об’єкт.", "<b>Shift + D</b> — з’явилася копія, вона рухається за мишкою.",
         "<b>X</b> (або Y, Z) і число, напр. " + c("2") + " → <b>Enter</b>."], w=900, size=32, gap=22)
K.render_img(s, 1080, 210, 712, P_STAIRS, label="сходи: кожен кубик — Shift + D і зсув на 2")
with s.frame():
    s.note(760, "Права кнопка після Shift + D — копія лишиться <b>в тому самому місці</b>, що й оригінал.", size=30)

s = d.now("Зроби зараз: сходи дублюванням",
          "Від пірамідки — до сходів. Кожну нову сходинку робимо Shift + D і зсувом.\n"
          "Зарахувати: 10 кубів, 4 стовпчики висотою 1, 2, 3, 4; без проміжків.", minutes=6)
s.steps(["Новий файл. Куб на <b>(0, 0, 1)</b>.",
         "<b>Shift + D</b>, <b>X</b>, " + c("2") + ", Enter — друга сходинка.",
         "На неї — копія вгору: <b>Shift + D</b>, <b>Z</b>, " + c("2") + ", Enter.",
         "Зробіть 4 стовпчики висотою <b>1, 2, 3, 4</b> куби.",
         "Збережіть " + c("Сходи — Прізвище.blend") + "."], w=900, size=29, gap=14)
