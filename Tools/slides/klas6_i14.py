def flat(name, **kw):
    os.makedirs(ASSETS, exist_ok=True)
    p = os.path.join(ASSETS, name)
    h.land_flat(**kw).save(p)
    return p


def plate(s, x, y, png, w=420, bg="rgba(255,255,255,0.28)", label=""):
    """Прозора «плівка» в перспективі: картинка на напівпрозорому аркуші, нахилена як стос."""
    s.raw(f'<div style="position:absolute;left:{x}px;top:{y}px;width:{w}px;height:{int(w * 0.75)}px;'
          f'transform:perspective(1400px) rotateX(58deg) rotateZ(-28deg);transform-origin:50% 50%;'
          f'background:{bg};border:3px solid rgba(47,48,51,0.55);border-radius:6px;'
          f'box-shadow:0 18px 30px rgba(30,40,60,0.18)">'
          f'<img alt="" src="{data_uri(png)}" style="width:100%;height:100%;display:block"></div>')
    if label:
        s.text(x + w + 20, y + int(w * 0.3), 300, 50, label, size=28, weight=700, color=INK)


def mini_land(s, x, y, w, png):
    kwin(s, x, y, w, png, shadow=False)


