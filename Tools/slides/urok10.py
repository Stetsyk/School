def diamond(sl, cx, cy, w, h, text):
    sl.raw(f'<svg style="position:absolute;left:{cx - w // 2}px;top:{cy - h // 2}px" width="{w}" height="{h}" '
           f'viewBox="0 0 {w} {h}"><polygon points="{w // 2},3 {w - 3},{h // 2} {w // 2},{h - 3} 3,{h // 2}" '
           f'fill="url(#g{cx})" stroke="#3E3F42" stroke-width="3"/><defs><linearGradient id="g{cx}" x1="0" x2="1">'
           f'<stop offset="0" stop-color="#A9CBF3"/><stop offset="1" stop-color="#E3EEFB"/></linearGradient></defs></svg>')
    sl.text(cx - w // 2 + 40, cy - 40, w - 80, 80, text, size=28, weight=700, align="center", valign="center",
            mono=True)


def arrow(sl, x1, y1, x2, y2, label=None, lx=0, ly=0):
    sl.raw(f'<svg style="position:absolute;left:0px;top:0px" width="1920" height="1080" viewBox="0 0 1920 1080">'
           f'<defs><marker id="ah" markerWidth="12" markerHeight="12" refX="9" refY="6" orient="auto">'
           f'<path d="M0,0 L12,6 L0,12 z" fill="#3E3F42"/></marker></defs>'
           f'<path d="M{x1} {y1} L{x2} {y2}" stroke="#3E3F42" stroke-width="4" fill="none" marker-end="url(#ah)"/></svg>')
    if label:
        sl.text(lx, ly, 120, 40, label, size=26, weight=700, color=ORANGE if label == "ні" else BLUE)


