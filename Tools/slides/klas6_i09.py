def pic(s, x, y, w, h, squash=False, handles=False, corner_hl=False, side_hl=False, border=True):
    """Умовне «фото»: небо, сонце, пагорби. squash=True — розтягнуте без збереження пропорцій."""
    par = "none" if squash else "xMidYMid slice"
    bd = "border:2px solid #3E3F42;" if border else ""
    s.raw(f'<div style="position:absolute;left:{x}px;top:{y}px;width:{w}px;height:{h}px;{bd}box-sizing:border-box;'
          f'overflow:hidden;border-radius:4px"><svg width="100%" height="100%" viewBox="0 0 160 120" '
          f'preserveAspectRatio="{par}"><rect width="160" height="120" fill="#BFD8F5"/>'
          f'<circle cx="118" cy="34" r="16" fill="#F0A55E"/>'
          f'<path d="M0 92 Q40 58 80 86 T160 78 V120 H0 Z" fill="#7FB07A"/>'
          f'<path d="M0 104 Q50 84 100 100 T160 98 V120 H0 Z" fill="#5E9460"/></svg></div>')
    if handles:
        pts = [(0, 0), (.5, 0), (1, 0), (0, .5), (1, .5), (0, 1), (.5, 1), (1, 1)]
        for px, py in pts:
            corner = px in (0, 1) and py in (0, 1)
            hl = (corner and corner_hl) or (not corner and side_hl)
            col = ORANGE if hl else "#FFFFFF"
            sz = 26 if hl else 18
            s.raw(f'<div style="position:absolute;left:{x + px * w - sz / 2}px;top:{y + py * h - sz / 2}px;'
                  f'width:{sz}px;height:{sz}px;background:{col};border:3px solid #2F6FB7;box-sizing:border-box"></div>')


def wrap_page(s, x, y, w, h, mode, title=True):
    """Мініатюра сторінки з фото та одним із чотирьох видів обтікання."""
    s.raw(f'<div style="position:absolute;left:{x}px;top:{y}px;width:{w}px;height:{h}px;background:#FBFCFD;'
          f'border:2px solid #3E3F42;border-radius:8px;box-sizing:border-box;box-shadow:0 10px 30px rgba(30,40,60,0.18)"></div>')
    m = 26
    lw = w - 2 * m
    cy = y + m

    def line(lx, ly, ww, col="#AEB6C1"):
        s.raw(f'<div style="position:absolute;left:{lx}px;top:{ly}px;width:{ww}px;height:10px;border-radius:5px;'
              f'background:{col}"></div>')

    if title:
        s.raw(f'<div style="position:absolute;left:{x + m + lw * .25}px;top:{cy}px;width:{lw * .5}px;height:18px;'
              f'border-radius:9px;background:#4A4E55"></div>')
        cy += 36
    step = 22
    if mode == "inline":
        for i in range(3):
            line(x + m, cy, lw * (0.95 if i < 2 else .6)); cy += step
        line(x + m, cy + 30, lw * .3)
        pic(s, x + m + lw * .32, cy, 60, 44)
        line(x + m + lw * .32 + 70, cy + 30, lw - lw * .32 - 70)
        cy += 56
        for i in range(4):
            line(x + m, cy, lw * (0.95 if i < 3 else .5)); cy += step
    elif mode == "around":
        pw, ph = int(lw * .42), 110
        pic(s, x + m, cy, pw, ph)
        yy = cy
        while yy < cy + ph:
            line(x + m + pw + 16, yy, lw - pw - 16); yy += step
        while yy < y + h - m - 10:
            line(x + m, yy, lw); yy += step
    elif mode == "topbottom":
        for i in range(2):
            line(x + m, cy, lw); cy += step
        ph = 100
        pic(s, x + m + lw * .15, cy + 4, lw * .7, ph)
        cy += ph + 16
        while cy < y + h - m - 10:
            line(x + m, cy, lw); cy += step
    elif mode == "behind":
        s.raw(f'<div style="position:absolute;left:{x + 8}px;top:{y + 8}px;width:{w - 16}px;height:{h - 16}px;opacity:.45">'
              f'</div>')
        pic(s, x + m + 10, cy + 10, lw - 20, h - (cy - y) - m - 20, border=False)
        s.raw(f'<div style="position:absolute;left:{x + m + 10}px;top:{cy + 10}px;width:{lw - 20}px;'
              f'height:{h - (cy - y) - m - 20}px;background:rgba(251,252,253,0.55)"></div>')
        while cy < y + h - m - 10:
            line(x + m, cy, lw, "#5C626B"); cy += step


