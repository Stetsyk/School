d.plan(["Що ми вже вміємо", "Де що в Blender", "Бліц: клавіші", "Детектив: знайди помилку", "Модель з іншого файлу",
        "Зроби зараз: зимова вулиця", "Підсумковий тест", "Як оцінюємо"],
       notes="Темп швидкий: повторення — 15 хв, міні-проєкт — 20 хв, тест — 10 хв (або без світла — тест і план сцени).")

s = d.slide("Що ми вже вміємо",
            "Пробігаємо розділ уроками. Питаємо по рядку: «Що ми робили на цьому уроці? Яка клавіша головна?» — учні відповідають, "
            "учитель відкриває рядок.\nВисновок: від одного кубика — до анімованих сцен, відео й файлу для 3D-принтера.")
s.h2("Що ми вже вміємо")
s.table(128, 210, [180, 560, 180, 744], [["Урок", "Уміння", "Урок", "Уміння"],
                                         ["03–04", "3D-графіка, навігація, примітиви", "09", "Tab, фаска, матеріали, текстури"],
                                         ["05", "переміщення G, координати X Y Z", "10", "ПР 6: власна 3D-модель"],
                                         ["06", "масштаб S, обертання R", "11", "ключові кадри I, таймлайн"],
                                         ["07", "розмір = масштаб × 2, панель N", "12", "рух, камера-дрон, відео MP4"],
                                         ["08", "складені моделі, Ctrl + P", "13–14", "ПР 7: анімація; 3D-друк, STL"]],
        row_h=92, size=29)

how(d, "Де що в Blender",
    "Справжній скрін усього вікна — повторюємо, де що. Питаємо, показуючи номер: «Що тут?»\n"
    "1 — меню «Додати» (Shift + A): примітиви. 2 — інструменти: Перемістити, Обернути, Масштабувати. 3 — 3D-вікно (сцена). "
    "4 — «Структура»: усі об’єкти, ієрархія. 5 — «Властивості»: Розташування, Обертання, Масштаб, Модифікатори, Матеріал. "
    "6 — таймлайн: кадри й анімація.",
    ["<b>Додати</b>.", "Інструменти.", "<b>3D-вікно</b>.", "<b>Структура</b>.", "<b>Властивості</b>.", "<b>Таймлайн</b>."],
    UI, w_steps=460, size=28)

s = d.slide("Бліц: клавіші",
            "Гра: учитель називає дію — клас хором (або на картках) називає клавішу. Потім клік — відповіді.\n"
            "Можна змагання рядів: хто перший і правильно.")
s.h2("Бліц: клавіші")
qs = ["Перемістити", "Масштаб", "Обернути", "Копія", "Прив’язати", "Режим редагування", "Ключовий кадр", "Рендер"]
