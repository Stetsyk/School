from deck import c
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk

L = 15


def no_clean(code):
    return "\n".join(l for l in code.splitlines() if not l.strip().startswith("clean("))


WINTER = K.HOUSE + '''
_before = set(bpy.data.objects.keys())
''' + no_clean(K.TREE) + '''
for _o in bpy.data.objects:
    if _o.name not in _before and _o.type == "MESH":
        _o.location.x += 3.4
        _o.location.y += 0.6
_before = set(bpy.data.objects.keys())
''' + no_clean(K.SNOWMAN) + '''
for _o in bpy.data.objects:
    if _o.name not in _before and _o.type == "MESH":
        _o.location.x -= 3.3
        _o.location.y -= 1.2
look(bpy.data.objects.get("Camera"), (13, -15, 7.5), (0, 0, 1.6))
'''

P_WIN = K.zrazok(L, "зимова вулиця — будиночок, ялинка, сніговик", WINTER, samples=96)

UI = bk(K.HOUSE + 'select("Стіни")\nview(rot=(64, 0, 35), dist=12, target=(0, 0, 1.4))\n', ["mousemove 700 600"],
        parts=[(0, 0, 1366, 768)],
        marks=[(268, 31, 320, 51, "bottom"), (12, 94, 46, 430, "right"), (360, 160, 760, 470, "right"),
               (1132, 56, 1366, 250, "left"), (1132, 262, 1366, 640, "left"), (0, 692, 1128, 742, "top")])
APPEND = bk(K.PAWN + 'view(rot=(66, 0, 35), dist=6, target=(0, 0, 1))\n', ["mousemove 51 14", "click 1", "sleep 0.8"],
            parts=[(0, 0, 265, 290)],
            marks=[(37, 5, 68, 21, "right"), (37, 252, 256, 270, "right")])

d = K.deck(L, "", "")

s = d.title("3D", "Підсумок розділу", "3D-графіка в Blender · 9 клас", big_size=320, big_top=580,
            notes="Підсумковий урок: згадуємо все, що вміємо, граємо в бліц, шукаємо помилки, а потім збираємо «зимову вулицю» "
                  "з власних моделей попередніх уроків.")
