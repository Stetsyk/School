def browser_pair(s, x, y, size, gap=80, labels=True):
    """Той самий смайлик: ліворуч PNG 40×40, праворуч SVG — обидва розтягнуті браузером до size."""
    s.raw(f'<img alt="" src="{data_uri(SMILE_PNG)}" style="position:absolute;left:{x}px;top:{y}px;width:{size}px;'
          f'height:{size}px;image-rendering:pixelated;border:2px solid {DARK_BG};border-radius:10px;background:#fff;'
          f'box-sizing:border-box">')
    svg = g.SMILE_SVG.replace('width="40" height="40"', f'width="{size - 4}" height="{size - 4}"')
    s.raw(f'<div style="position:absolute;left:{x + size + gap}px;top:{y}px;width:{size}px;height:{size}px;'
          f'border:2px solid {DARK_BG};border-radius:10px;background:#fff;box-sizing:border-box;overflow:hidden">{svg}</div>')


def grid8(s, x, y, cell, fill=None, color="#D9342B", labels=True):
    """Сітка 8 × 8 з номерами рядків і стовпців (як у зошиті)."""
    fill = fill or set()
    for r in range(8):
        for cc in range(8):
            on = (r, cc) in fill
            s.raw(f'<div style="position:absolute;left:{x + cc * cell}px;top:{y + r * cell}px;width:{cell}px;height:{cell}px;'
                  f'background:{color if on else "#FBFCFD"};border:1.5px solid #9AA3AE;box-sizing:border-box"></div>')
    if labels:
        for i in range(8):
            s.text(x + i * cell, y - 38, cell, 34, str(i + 1), size=22, weight=700, align="center", color=INK2)
            s.text(x - 40, y + i * cell, 34, cell, str(i + 1), size=22, weight=700, align="center", valign="center",
                   color=INK2)


