def icon(s, x, y, png, cx, cy, size=90, half=13, label="", key=""):
    kwin(s, x, y, size, png, crop=(cx - half, cy - half, 2 * half, 2 * half), shadow=False)
    if label:
        s.text(x + size + 22, y, 360, size, [f"<b>{label}</b>", key], size=27, valign="center", lh=1.25)


def circles(s, x, y, size=180, gap=60, labels=True):
    specs = [("#F7CE46", "none", 0, "жовта · без обведення"), ("none", "#2F3033", 2, "без заливки · чорне 1"),
             ("#FFFFFF", "#D9342B", 10, "біла · червоне 5"), ("#2F6FB7", "#F7CE46", 6, "синя · жовте 3")]
    for k, (f, st, sw, lab) in enumerate(specs):
        xx = x + k * (size + gap)
        s.raw(f'<svg style="position:absolute;left:{xx}px;top:{y}px" width="{size}" height="{size}" viewBox="0 0 100 100">'
              f'<circle cx="50" cy="50" r="42" fill="{f}" stroke="{st}" stroke-width="{sw}"/></svg>')
        if labels:
            s.text(xx - 20, y + size + 10, size + 40, 70, f"<b>{k + 1}</b> · {lab}", size=23, align="center", color=INK2)


