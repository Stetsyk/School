def run_err(code):
    """Як run(), але помилку показує так, як її показав би Python."""
    import contextlib
    import io
    buf = io.StringIO()
    try:
        with contextlib.redirect_stdout(buf):
            exec(code, {})
    except Exception as e:
        return buf.getvalue() + f"{type(e).__name__}: {e}"
    return buf.getvalue().rstrip("\n")


