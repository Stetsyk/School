def t(body, bg=None):
    pre = "import turtle\n"
    if bg:
        pre += f'turtle.bgcolor("{bg}")\n'
    return pre + "\n" + body.strip() + "\n\nturtle.hideturtle()\nturtle.done()\n"


SQUARE = '''def квадрат(сторона, колір):
    turtle.fillcolor(колір)
    turtle.begin_fill()
    for i in range(4):
        turtle.forward(сторона)
        turtle.right(90)
    turtle.end_fill()'''

GOTO = '''def перейти(x, y):
    turtle.penup()
    turtle.goto(x, y)
    turtle.pendown()'''

CIRCLE = '''def коло(x, y, радіус, колір):
    перейти(x, y - радіус)
    turtle.fillcolor(колір)
    turtle.begin_fill()
    turtle.circle(радіус)
    turtle.end_fill()'''

TRI = '''def трикутник(сторона, колір):
    turtle.fillcolor(колір)
    turtle.begin_fill()
    for i in range(3):
        turtle.forward(сторона)
        turtle.left(120)
    turtle.end_fill()'''

TREE = '''def ялинка(x, y):
    перейти(x - 10, y)
    квадрат(20, "sienna")
    перейти(x - 50, y)
    трикутник(100, "forestgreen")
    перейти(x - 40, y + 50)
    трикутник(80, "green")'''

SNOWMAN = '''def сніговик(x, y):
    коло(x, y, 60, "white")
    коло(x, y + 95, 42, "white")
    коло(x, y + 160, 28, "white")
    коло(x - 10, y + 166, 4, "black")
    коло(x + 10, y + 166, 4, "black")'''

ALL = "\n\n".join([GOTO, SQUARE, TRI, CIRCLE, TREE, SNOWMAN])

