def t(body, bg=None, hide=True, seed=None):
    pre = "import turtle\n"
    if "random" in body:
        pre += "import random\n"
        if seed is not None:
            pre += f"random.seed({seed})\n"
    pre += '\nturtle.shape("turtle")\n'
    if bg:
        pre += f'turtle.bgcolor("{bg}")\n'
    end = "\nturtle.hideturtle()" if hide else ""
    return pre + body.strip() + end + "\n\nturtle.done()\n"


