s.card(1300, 200, 492, 620, "Види",
       ["<b>1</b> — спереду.", "<b>3</b> — збоку.", "<b>7</b> — зверху.", "<b>5</b> — перспектива.", "",
        "Без цифр: <b>Огляд → Точка огляду</b>."], kind="blue", title_size=34, body_size=30, valign="flex-start")

