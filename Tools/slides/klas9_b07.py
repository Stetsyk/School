FRONT = bk(K.TABLE + K.CHAIR + 'select("Ніжка 1")\n' + 'view(rot=(64, 0, 35), dist=9, target=(0, -0.8, 0.8))\n',
           ["mousemove 500 400", "key KP_1", "sleep 1.0", "mousemove 500 640"],
           parts=[(50, 84, 700, 446)], marks=[(62, 90, 220, 108, "bottom"), (434, 404, 460, 440, "left")])

d = K.deck(L, "", "")

s = d.title("2 м", "Моделі з примітивів", "Стіл, стілець і точні розміри · 9 клас", big_size=300, big_top=590,
            notes="Сьогодні збираємо справжні речі — стіл і стілець — з витягнутих кубів. Головне відкриття уроку: "
                  "куб у Blender має сторону 2 м, тому масштаб = розмір : 2.")
K.render_img(s, 1180, 150, 620, P_SET)

d.plan(["Розібрати річ на примітиви", "Куб — 2 метри!", "Бічна панель N: «Розмірності»", "Зроби зараз: стіл",
        "Перевірка спереду: цифра 1", "Зроби зараз: стілець", "Практика й оцінювання"],
       notes="Наскрізна історія: облаштовуємо куточок класу — спершу стіл, потім стілець, а сильні — шафу чи полицю.")

s = d.slide("Розібрати річ на примітиви",
            "Гачок: покажіть на справжній стіл у класі. Питаємо: «З яких простих тіл він складається?» → стільниця (плаский "
            "прямокутник) і 4 ніжки (довгі тонкі бруски). Усе це — куби з різним масштабом.\n"
            "3D-моделлер спершу «розбирає» річ подумки, записує розміри — і лише тоді сідає за комп’ютер.\n"
            "Питаємо: «А стілець?» → сидіння, спинка, 4 ніжки — 6 кубів.")
s.h2("Розібрати річ на примітиви")
