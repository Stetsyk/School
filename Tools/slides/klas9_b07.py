"""9 клас, урок ІІ-07. Створення просторових моделей з примітивів.
Скріни — справжній Blender: бічна панель N («Масштаб» і «Розмірності»), вигляд «Спереду Ортогонально» (цифра 1)."""
from deck import c
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk, AWAY

L = 7
P_TABLE = K.zrazok(L, "стіл", K.TABLE)
P_SET = K.zrazok(L, "стіл і стілець (рівень 2)", K.TABLE + K.CHAIR)

VT = 'view(rot=(64, 0, 35), dist=9, target=(0, 0, 0.8))\n'
