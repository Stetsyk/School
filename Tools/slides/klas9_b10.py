s.h2("Що здаємо")
s.steps(["Модель із <b>5+ примітивів</b> (варіант А, Б або свій).",
         "Кожна деталь має <b>назву</b> (Основа, Тулуб…).",
         "Деталі <b>прив’язані</b> до головної (Ctrl + P) — модель рухається цілою.",
         "Хоча б <b>2 матеріали</b>; кулі й циліндри — <b>Згладжене тонування</b>.",
         "Файли: " + c("ПР6 — Прізвище.blend") + " і рендер " + c("ПР6 — Прізвище.png") + "."], w=1100, size=31, gap=18)
