s = d.slide("Пам’ятка клавіш",
            "Повторюємо все, що знадобиться. Питаємо бліцом: «Перемістити?» → G. «Масштаб?» → S. «Обернути?» → R. "
            "«Копія?» → Shift + D. «Прив’язати?» → Ctrl + P. «Точні розміри?» → N. «Рендер?» → F12.\n"
            "Пам’ятку можна залишити на екрані під час роботи.")
