def tile(kind, w=420, hgt=260):
    """Один і той самий строкатий фон-трава; напис по-різному (для слайда «Щоб напис було видно»)."""
    bg = h.poster_patient(1000).crop((300, 200, 300 + w * 1000 // 1000, 200 + hgt))
    im = bg.convert("RGBA")
    d_ = ImageDraw.Draw(im, "RGBA")
    f = ImageFont.truetype(BOLD, 58)
    cx, cy = w // 2, hgt // 2
    if kind == "bad":
        d_.text((cx, cy), "Змагання", font=ImageFont.truetype(h.INTER_THIN, 64), fill="#B9E6A8", anchor="mm")
    elif kind == "contrast":
        d_.text((cx, cy), "Змагання", font=f, fill="#FFFFFF", anchor="mm")
    elif kind == "pad":
        d_.rounded_rectangle((cx - 190, cy - 52, cx + 190, cy + 52), 18, fill=(31, 42, 68, 200))
        d_.text((cx, cy), "Змагання", font=f, fill="#FFFFFF", anchor="mm")
    else:  # outline
        d_.text((cx, cy), "Змагання", font=f, fill="#FFFFFF", anchor="mm", stroke_width=5, stroke_fill="#1F2A44")
    return save(im.convert("RGB"), f"napys_{kind}.png")


