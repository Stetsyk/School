"""9 клас, урок ІІ-14. 3D-друк: як працює принтер, правила моделі для друку, масштаб, експорт STL, товщина стінок.
Скрін — справжній Blender: «Файл → Експортувати → Stl (.stl)». Додатки: .blend, .png і готові .stl для слайсера."""
from deck import c
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk

L = 14

CUP = '''
import bmesh
clean(cam=(5.5, -5.5, 4.2), target=(0, 0, 0.9))
o = add("cylinder", "Склянка для олівців", loc=(0, 0, 1), scale=(0.8, 0.8, 1), color="#2F6FB7", vertices=6)
bm = bmesh.new(); bm.from_mesh(o.data)
bmesh.ops.delete(bm, geom=[f for f in bm.faces if f.normal.z > 0.9], context="FACES")
bm.to_mesh(o.data); bm.free()
_m = o.modifiers.new("Потовщення", "SOLIDIFY")
_m.thickness = 0.1
_m.offset = -1
'''

P_PAWN = K.zrazok(L, "пішка для друку (STL, масштаб 20 — 46 мм)", K.PAWN, stl=True, stl_scale=20.0)
P_CUP = K.zrazok(L, "склянка для олівців (STL, масштаб 50 — 10 см)", CUP, stl=True, stl_scale=50.0)

EXPORT = bk(K.PAWN + 'view(rot=(66, 0, 35), dist=6, target=(0, 0, 1))\n',
            ["mousemove 51 14", "click 1", "sleep 0.8", "mousemove 100 331", "sleep 1.2"],
            parts=[(0, 0, 500, 500)],
            marks=[(31, 5, 70, 22, "right"), (34, 322, 258, 342, "left"), (266, 405, 490, 425, "right")])

d = K.deck(L, "", "")

s = d.title("STL", "3D-друк", "Від моделі до справжньої речі · 9 клас", big_size=300, big_top=590,
            notes="Сьогодні дізнаємося, як 3D-модель з комп’ютера стає річчю, яку можна взяти в руки, і підготуємо до друку "
                  "свою пішку з ПР 6. Якщо в школі немає принтера — файл STL можна надрукувати в бібліотеці, ЦДЮТ чи сервісі друку.")
K.render_img(s, 1180, 150, 620, P_PAWN)

d.plan(["Як працює 3D-принтер", "Від Blender до принтера", "Правила моделі для друку", "Масштаб: метри й міліметри",
        "Експорт STL", "Товщина стінок", "Зроби зараз", "Практика й оцінювання"],
       notes="Головне вміння уроку — правильно експортувати STL потрібного розміру. Решта — розуміння, як працює друк.")

s = d.slide("Як працює 3D-принтер",
            "Найпоширеніший шкільний принтер — FDM: пластикова нитка (філамент) розплавляється в гарячому соплі (≈ 200 °C), "
            "і принтер «малює» річ шар за шаром, знизу вгору, як торт із коржів. Товщина шару — зазвичай 0.2 мм.\n"
            "Питаємо: «Пішка заввишки 46 мм, шар 0.2 мм. Скільки шарів?» → 230. «Чому друк триває годинами?» → кожен шар "
            "малюється окремо.")
s.h2("Як працює 3D-принтер")
s.steps(["Пластикова <b>нитка</b> (PLA) намотана на котушку.", "<b>Сопло</b> гріється до ≈ 200 °C і плавить пластик.",
         "Принтер малює <b>шар</b> 0.2 мм, піднімається — і наступний.", "Знизу вгору, як <b>торт із коржів</b>."],
        w=1000, size=31, gap=18)
s.card(1200, 220, 592, 280, "Питання", ["Пішка <b>46 мм</b>, шар <b>0.2 мм</b>.", "Скільки шарів?"], kind="light",
       title_size=34, body_size=31, valign="flex-start")
with s.frame("pop"):
    s.card(1200, 540, 592, 260, "Відповідь", ["46 : 0.2 = <b>230</b> шарів.", "Тому друк — годинами."], kind="orange",
           title_size=34, body_size=31, valign="flex-start")

s = d.slide("Від Blender до принтера",
            "Ланцюжок однаковий для всіх принтерів. Blender — модель. STL — формат, який розуміють усі програми друку (лише "
            "форма, без кольорів і матеріалів!). Слайсер (Cura, PrusaSlicer, Bambu Studio — безкоштовні) «нарізає» модель на шари "
            "й рахує час і пластик. Результат — файл G-code для принтера.\n"
            "Питаємо: «Чи збережеться в STL золотий колір кулі?» → ні, тільки форма. Колір дає пластик.")
s.h2("Від Blender до принтера")
for k, (t, sub) in enumerate([("Blender", "модель"), ("STL", "лише форма"), ("Слайсер", "шари, час, пластик"),
                              ("Принтер", "G-code → річ")]):
    s.card(128 + k * 424, 260, 380, 260, t, [sub], kind="blue" if k % 2 == 0 else "light", title_size=40, body_size=30,
           valign="flex-start")
    if k < 3:
        s.text(128 + k * 424 + 382, 340, 42, 80, "→", size=56, weight=800, color="#E8772E")
with s.frame("pop"):
    s.note(640, "STL зберігає <b>лише форму</b>: кольори й матеріали Blender не друкуються.", size=32)

s = d.slide("Правила моделі для друку",
            "П’ять правил, без яких друк не вдасться.\n1) Замкнена поверхня: без дірок (наша склянка — з товщиною стінок, а не "
            "«папірець»). 2) Пласка основа: модель стоїть на столі принтера. 3) Нічого не висить у повітрі — інакше потрібні опори. "
            "4) Стінки не тонші за 1–2 мм. 5) Розмір — у міліметрах, не більший за стіл принтера (≈ 20 × 20 см).\n"
            "Питаємо: «Чи надрукується сніговик з носом-конусом?» → так, але ніс бажано з опорою або коротший.")
s.h2("Правила моделі для друку")
for k, (t, sub) in enumerate([("1. Замкнена", "без дірок і «папірців»"), ("2. Пласка основа", "стоїть на столі"),
                              ("3. Не висить", "або потрібні опори"), ("4. Стінки ≥ 1–2 мм", "тонке зламається"),
                              ("5. Розмір у мм", "до ≈ 20 × 20 см")]):
    s.card(128 + (k % 3) * 560, 230 + (k // 3) * 300, 520, 260, t, [sub], kind="light" if k % 2 else "blue",
           title_size=36, body_size=30, valign="flex-start")
K.render_img(s, 1248, 530, 400, P_CUP)

s = d.slide("Масштаб: метри й міліметри",
            "Пастка! Blender рахує в метрах, а слайсер читає числа STL як міліметри. Пішка заввишки 2.3 м у Blender стане "
            "в слайсері… 2.3 мм — менше рисової зернини.\nРішення: у вікні експорту STL поле «Масштаб». Масштаб 20 → 2.3 × 20 = 46 мм.\n"
            "Питаємо: «Склянка 2 м заввишки, хочу 10 см. Який Масштаб?» → 100 мм : 2 = 50.")
s.h2("Масштаб: метри й міліметри")
s.text(128, 230, 1664, 110, "Розмір у мм = розмір у Blender × Масштаб", size=58, weight=800, color="#2F6FB7")
s.table(128, 380, [420, 420, 420, 404], [["Модель", "У Blender", "Масштаб", "Надрукується"],
                                         ["Пішка", "2.3", "20", "46 мм"], ["Склянка", "2", "?", "100 мм"],
                                         ["Брелок", "1", "30", "30 мм"]], row_h=90, size=32)
with s.frame("pop"):
    s.note(780, "Склянка: 100 : 2 = <b>50</b>.", size=34)

how(d, "Експорт STL",
    "Справжній скрін. 1 — «Файл», 2 — «Експортувати», 3 — «Stl (.stl)». Відкриється вікно збереження: праворуч "
    "налаштування — «Масштаб» (наприклад 20), «Лише вибране» (якщо в сцені є зайве — підлога, камера) і «Застосувати "
    "модифікатори» (щоб товщина стінок і фаска потрапили в STL).\nІм’я файлу — латиницею або українською, розширення .stl.\n"
    "Перевірити STL: відкрити у слайсері (Cura) або в онлайн-переглядачі.",
    ["<b>Файл</b>.", "<b>Експортувати</b>.", "<b>Stl (.stl)</b> → Масштаб, Лише вибране."], EXPORT, w_steps=640, size=30)

s = d.slide("Товщина стінок",
            "Склянка з циліндра без кришки — це «папірець» нульової товщини: принтер його не надрукує. Модифікатор «Потовщення» "
            "додає стінкам товщину.\nКроки: Tab → 3 (грані) → клацнути верхню грань → X → «Грані» (дірка зверху). Tab. Вкладка "
            "«Модифікатори» → Додати модифікатор → Генерування → «Потовщення», «Товщина» 0.1 (× 50 = 5 мм).\n"
            "Питаємо: «Товщина 0.02 і масштаб 50 — скільки мм?» → 1 мм, на межі; краще 0.04+.")
s.h2("Товщина стінок")
s.steps(["<b>Tab</b> → <b>3</b> → верхня грань → <b>X → Грані</b>. <b>Tab</b>.",
         "<b>Модифікатори → Додати модифікатор → Генерування → Потовщення</b>.",
         "<b>Товщина</b>: " + c("0.1") + " (з Масштабом 50 — це 5 мм)."], w=1000, size=30, gap=18)
K.render_img(s, 1180, 216, 612, P_CUP, label="склянка: стінки 5 мм")

s = d.now("Зроби зараз: пішка в STL",
          "Беремо пішку з ПР 6 (або зразок з «Додатків»). Хочемо 46 мм заввишки.\nЗарахувати: файл «Пішка — Прізвище.stl»; "
          "у слайсері / переглядачі висота ≈ 46 мм; підлоги й камери в STL немає.", minutes=6)
s.steps(["Відкрийте " + c("ПР6 — Прізвище.blend") + ". Виділіть усі деталі пішки (не підлогу).",
         "<b>Файл → Експортувати → Stl (.stl)</b>.",
         "Праворуч: <b>Масштаб</b> " + c("20") + ", <b>Лише вибране</b> ✓, <b>Застосувати модифікатори</b> ✓.",
         "Назва " + c("Пішка — Прізвище.stl") + " → <b>Експортувати STL</b>.",
         "⭐ Відкрийте STL у Cura або онлайн-переглядачі: яка висота?"], w=1000, size=28, gap=12)
K.render_img(s, 1180, 216, 612, P_PAWN, label="пішка: 2.3 × 20 = 46 мм")

d.your_turn([("star", "Оберіть свій рівень"), ("book", "Без світла 1: надрукується?"),
             ("edit", "Без світла 2: шари й масштаб"), ("chart", "Як оцінюємо")],
            notes="Домашнє завдання: знайти, де поблизу можна надрукувати STL (школа, бібліотека, ЦДЮТ, сервіс), і скільки це коштує.")

d.levels([("Пішка в STL", "до 6 балів", ["Масштаб 20.", "Лише вибране.", "Файл .stl збережено."]),
          ("Склянка", "до 9 балів", ["Без кришки + Потовщення.", "Стінки ≥ 2 мм.", "STL на 10 см."]),
          ("Своя річ для друку", "до 12 балів", ["Брелок, підставка, фігурка.", "Усі 5 правил друку.",
                                                "Перевірено в слайсері: час і пластик."])],
         notes="Рівень 3: просимо скрін зі слайсера (час друку й маса пластику) — це перевірка, що модель справді друкується.")

s = d.task("Без світла 1: надрукується?",
           "Відповіді: 1 — так; 2 — ні (немає товщини, правило 1/4); 3 — потрібні опори (правило 3); 4 — ні, 2.3 мм (правило 5); "
           "5 — ні, стінка 0.5 мм (правило 4).\nБали: 5 правильних — 3; 3–4 — 2.", where="У зошиті")
s.steps(["Чи надрукується? Напишіть «так» / «ні» і номер порушеного правила (1–5)."], w=1664, size=30)
for k, t in enumerate(["1) Куб 2 × 2 × 2 м, експорт з масштабом 10.", "2) Площина (тонкий аркуш) без товщини.",
                       "3) Літак, крила якого висять у повітрі.", "4) Пішка 2.3 м, експорт з масштабом 1.",
                       "5) Склянка зі стінками 0.01 і масштабом 50."]):
    s.card(128, 300 + k * 120, 1100, 100, None, t, kind="light", body_size=30)
s.card(1280, 300, 512, 580, "Правила", ["1 замкнена", "2 пласка основа", "3 не висить", "4 стінки ≥ 1–2 мм",
                                         "5 розмір у мм"], kind="blue", title_size=34, body_size=30, valign="flex-start")

s = d.task("Без світла 2: шари й масштаб",
           "Відповіді: а) 46 мм; б) 230 шарів; в) масштаб 50; г) 150 шарів (30 : 0.2); д) 5 мм.\n"
           "Бали: 5 правильних — 3; 3–4 — 2.", where="У зошиті")
s.steps(["Розмір у мм = розмір у Blender × Масштаб. Шар = 0.2 мм."], w=1664, size=30)
for k, t in enumerate(["а) Пішка 2.3, Масштаб 20. Висота в мм?", "б) Скільки шарів у пішці з пункту «а»?",
                       "в) Склянка 2, хочу 100 мм. Масштаб?", "г) Брелок 30 мм заввишки. Скільки шарів?",
                       "д) Товщина 0.1, Масштаб 50. Стінка в мм?"]):
    s.card(128, 300 + k * 120, 1100, 100, None, t, kind="light", body_size=30)
K.render_img(s, 1290, 300, 502, P_PAWN)

K.zrazky_slide(d, L)

d.rubric([("Принтер і шари", "FDM, шар 0.2 мм, рахує шари", "2"),
          ("Правила друку", "5 правил, знаходить порушення", "2"),
          ("Масштаб", "мм = Blender × Масштаб", "2"),
          ("Експорт STL", "Файл → Експортувати, Лише вибране", "3"),
          ("Склянка / своя річ", "Потовщення, перевірено", "3")], total="12",
         notes="Без світла: надрукується? — 3, шари й масштаб — 3, ланцюжок Blender → STL → слайсер → принтер — 3, усно правила — 3.")

K.save(d, L)
