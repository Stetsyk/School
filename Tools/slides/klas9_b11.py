d.rubric([("Таймлайн", "Кадр, Кінець, Грати", "2"),
          ("Ключі I", "правильне меню, жовті поля", "2"),
          ("Кадри й секунди", "24 кадри = 1 с", "2"),
          ("Обертання", "повний оберт 1 → 72", "3"),
          ("Пульсація / свій ефект", "масштаб або колір", "3")], total="12",
         notes="Без світла: рахуємо кадри — 3, розкадровка — 3, таблиця ключів для своєї моделі — 3, бліц «жовте чи зелене?» — 3.")

