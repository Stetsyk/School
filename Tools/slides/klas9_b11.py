"""9 клас, урок ІІ-11. Анімаційні ефекти: ключові кадри, таймлайн, клавіша I, кольори полів.
Скріни — справжній Blender: таймлайн (Кадр, Кінець, Грати), меню «Вставляння ключового кадру», жовті й зелені поля."""
from deck import c
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk

L = 11

COLOR = '''
clean(cam=(7, -7, 4.5), target=(0, 0, 1))
b = add("uv_sphere", "Куля", loc=(0, 0, 1), segments=48, ring_count=24)
bpy.context.view_layer.objects.active = b
bpy.ops.object.shade_smooth()
m = mat(b, (0.85, 0.2, 0.15), "Колір, що змінюється", rough=0.3)
_bs = next(n for n in m.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
_inp = _bs.inputs["Base Color"]
sc = bpy.context.scene
sc.frame_start, sc.frame_end = 1, 72
for _f, _col in [(1, (0.85, 0.2, 0.15, 1)), (24, (0.95, 0.8, 0.1, 1)), (48, (0.15, 0.4, 0.9, 1)), (72, (0.85, 0.2, 0.15, 1))]:
    _inp.default_value = _col
    _inp.keyframe_insert("default_value", frame=_f)
b.location = (0, 0, 1); b.keyframe_insert("location", frame=1)
b.location = (0, 0, 2); b.keyframe_insert("location", frame=36)
b.location = (0, 0, 1); b.keyframe_insert("location", frame=72)
'''

P_SPIN = K.zrazok(L, "куб обертається й пульсує", K.SPIN, anim=".mp4")
P_COLOR = K.zrazok(L, "куля змінює колір і підстрибує (рівень 3)", COLOR, anim=".mp4")

S = K.SPIN + 'select("Куб")\nbpy.context.scene.frame_set(36)\nview(rot=(64, 0, 35), dist=9, target=(0, 0, 1))\n'
TL = bk(S, ["mousemove 500 640"], parts=[(560, 692, 1128, 719), (0, 719, 568, 742)],
        marks=[(816, 696, 890, 715, "top"), (1022, 696, 1116, 715, "top"), (576, 696, 596, 716, "top"),
               (174, 722, 203, 739, "top")])
IMENU = bk(S, ["mousemove 500 400", "key i", "sleep 0.8"], layout="row",
           parts=[(250, 150, 620, 500), (1132, 440, 1366, 625)],
           marks=[(262, 329, 560, 351, "right"), (264, 402, 554, 421, "right"), (1176, 464, 1306, 526, "left")])
FIELDS = bk(S, ["mousemove 500 640"], parts=[(1132, 380, 1366, 625)],
            marks=[(1240, 464, 1308, 526, "left"), (1240, 556, 1308, 620, "left"), (1326, 462, 1346, 622, "right")])

d = K.deck(L, "", "")

s = d.title("I ◆", "Анімаційні ефекти", "Ключові кадри · 9 клас", big_size=320, big_top=580,
            notes="Сьогодні наші моделі оживуть: обертання, пульсація, зміна кольору. Головне слово уроку — ключовий кадр. "
                  "Ми задаємо лише кілька «опорних» станів, а всі кадри між ними Blender домальовує сам.")
K.render_img(s, 1180, 150, 620, P_SPIN)

d.plan(["Мультфільм — це кадри", "Ключові кадри", "Таймлайн", "Ключ: клавіша I", "Жовте й зелене поле",
        "Зроби зараз: обертання", "Зроби зараз: пульсація", "Практика й оцінювання"],
       notes="Наскрізна історія: «оживляємо» кубик — спершу обертання, потім пульсація, а сильні — зміна кольору.")

s = d.slide("Мультфільм — це кадри",
            "Гачок: питаємо «Скільки малюнків треба для мультика тривалістю 3 секунди?» → у кіно 24 кадри за секунду, тож 72.\n"
            "Раніше аніматори малювали кожен кадр вручну. У Blender ми ставимо лише ключові кадри (початок і кінець руху), "
            "а проміжні він обчислює сам. Це називається інтерполяція.\nПитаємо: «А 5 секунд?» → 120 кадрів.")
s.h2("Мультфільм — це кадри")
s.text(128, 240, 1664, 140, "24 кадри = 1 секунда", size=88, weight=800, color="#2F6FB7")
s.card(128, 430, 800, 300, "Питання", ["Мультик на <b>3 секунди</b>.", "Скільки кадрів?"], kind="light", title_size=34,
       body_size=34, valign="flex-start")
with s.frame("pop"):
    s.card(992, 430, 800, 300, "Відповідь", ["3 × 24 = <b>72</b> кадри.", "А малюємо лише <b>ключові</b>!"],
           kind="orange", title_size=34, body_size=34, valign="flex-start")

s = d.slide("Ключові кадри",
            "Ключовий кадр — «фото» стану об’єкта в певний момент: де він, як повернутий, якого розміру.\n"
            "Приклад: кадр 1 — Обертання Z = 0°, кадр 72 — 360°. На кадрі 36 Blender сам поверне куб приблизно на 180°.\n"
            "Питаємо: «Що буде на кадрі 18?» → приблизно 90° (чверть оберту).")
s.h2("Ключові кадри")
s.table(128, 220, [420, 420, 420, 404], [["Кадр", "1", "36", "72"], ["Обертання Z", "0°", "≈ 180°", "360°"],
                                         ["Хто задав", "<b>ми</b> — ключ", "Blender сам", "<b>ми</b> — ключ"]],
        row_h=100, size=34)
K.render_img(s, 128, 600, 600, P_SPIN)
with s.frame("pop"):
    s.card(800, 600, 992, 230, "Кадр 18?", ["Приблизно <b>90°</b> — чверть оберту."], kind="orange", title_size=34,
           body_size=32, valign="flex-start")

how(d, "Таймлайн",
    "Справжній скрін таймлайну — смужки внизу вікна. 1 — «Кадр»: номер поточного кадру (тут 36); можна вписати число. "
    "2 — «Кінець»: скільки кадрів у анімації (72 = 3 с). 3 — «Грати» (або пробіл): програти анімацію; ще раз пробіл — стоп. "
    "4 — синій бігунок: перетягніть мишкою — анімація «прокручується».\n"
    "Shift + ← — на початок.\nТипова хиба: забули змінити «Кінець» з 250 на 72 — після оберту куб довго стоїть.",
    ["Поле <b>Кадр</b>.", "<b>Кінець</b>: " + c("72") + ".", "<b>Грати</b> / пробіл.", "Бігунок кадрів."], TL,
    side=False, size=29)

how(d, "Ключ: клавіша I",
    "Справжній скрін. Мишка над сценою, об’єкт виділено → I. 1 — меню «Вставляння ключового кадру». 2 — «Обертання» (або "
    "«Розташування», «Масштаб»). 3 — поля «Обертання» у «Властивостях» стали жовтими: на цьому кадрі є ключ.\n"
    "Порядок завжди: 1) кадр, 2) змінити значення, 3) I → що запам’ятати.\n"
    "Питаємо: «Хочу, щоб куб і рухався, і крутився. Що обрати в меню?» → «Локація та Обертання».",
    ["Мишка над сценою → <b>I</b>.", "Оберіть: <b>Обертання</b>, Розташування чи Масштаб.",
     "Поля стали <b>жовтими</b> — ключ є."], IMENU, w_steps=560, size=30)

how(d, "Жовте й зелене поле",
    "Справжній скрін на кадрі 36. Кольори полів підказують, що відбувається:\n"
    "1 — зелене поле: значення анімоване, але на цьому кадрі ключа немає (Blender обчислив сам). "
    "2 — жовте: на цьому кадрі стоїть ключ. 3 — ромбик праворуч: клацнути — поставити ключ саме для цього поля "
    "(без меню I). Заповнений ромб — ключ є, порожній — немає.\n"
    "Типова хиба: змінили жовте поле й перейшли на інший кадр — зміна зникла. Треба ще раз I (або ромбик).",
    ["<b>Зелене</b> — анімовано, ключа тут нема.", "<b>Жовте</b> — ключ на цьому кадрі.",
     "<b>Ромбик</b> — поставити ключ одним кліком."], FIELDS, w_steps=760, size=31)

s = d.now("Зроби зараз: куб обертається",
          "Новий файл, стартовий куб. Таймлайн — унизу вікна.\nЗарахувати: Кінець = 72; ключі на кадрах 1 і 72; пробіл — куб "
          "робить повний оберт навколо Z; файл «Анімація — Прізвище.blend».", minutes=6)
s.steps(["Таймлайн: <b>Кінець</b> = " + c("72") + ". <b>Кадр</b> = " + c("1") + ".",
         "Виділіть куб, мишка над сценою — <b>I → Обертання</b>.",
         "<b>Кадр</b> = " + c("72") + ". У «Властивостях» <b>Обертання Z</b> = " + c("360") + ".",
         "<b>I → Обертання</b>. Пробіл — дивимось!", "Збережіть " + c("Анімація — Прізвище.blend") + "."],
        w=1000, size=29, gap=14)
K.render_img(s, 1180, 216, 612, P_SPIN, label="зразок: обертання")

s = d.slide("Плавно чи рівномірно?",
            "Помітили: куб розганяється на початку й гальмує в кінці? Так задумано: Blender за замовчуванням робить рух «плавним», "
            "як у справжніх речей (машина не рушає миттєво).\n"
            "Для вічного обертання (вітряк, планета) потрібен рівномірний рух — інтерполяція «Лінійна». У вікні «Аркуш "
            "доповідей» (Dope Sheet): A — виділити всі ключі, T → «Лінійна».\nПитаємо: «Що має рухатися рівномірно: м’яч, "
            "вітряк, ліфт?» → вітряк.")
s.h2("Плавно чи рівномірно?")
s.card(128, 220, 800, 520, "Плавно (за замовчуванням)", ["Розгін → рух → гальмування.", "Машина, ліфт, двері.",
                                                          "Так рухаються речі в житті."], kind="blue", title_size=36,
       body_size=31, valign="flex-start")
s.card(992, 220, 800, 520, "Рівномірно — «Лінійна»", ["Однакова швидкість.", "Вітряк, планета, колесо.",
                                                       "Аркуш доповідей: <b>A</b>, <b>T → Лінійна</b>."], kind="light",
       title_size=36, body_size=31, valign="flex-start")
with s.frame("pop"):
    s.note(800, "Рівномірно крутиться <b>вітряк</b>. М’яч і ліфт — плавно.", size=32)

s = d.now("Зроби зараз: пульсація",
          "Продовжуємо файл з обертанням: додаємо ключі масштабу. Три ключі — на кадрах 1, 36, 72.\n"
          "Зарахувати: куб збільшується в середині анімації й повертається до розміру 1; обертання збереглося.", minutes=5)
s.steps(["<b>Кадр 1</b>: Масштаб 1 · 1 · 1 → <b>I → Масштаб</b>.",
         "<b>Кадр 36</b>: Масштаб " + c("1.4") + " (усі три) → <b>I → Масштаб</b>.",
         "<b>Кадр 72</b>: Масштаб " + c("1") + " → <b>I → Масштаб</b>.",
         "Пробіл. Куб «дихає» й крутиться. <b>Ctrl + S</b>."], w=1000, size=30, gap=16)
s.table(128, 650, [300, 220, 220, 220], [["Кадр", "1", "36", "72"], ["Масштаб", "1", "1.4", "1"],
                                         ["Обертання Z", "0°", "—", "360°"]], row_h=64, size=27)
K.render_img(s, 1180, 216, 612, P_SPIN, label="зразок: обертання + пульсація")

d.your_turn([("star", "Оберіть свій рівень"), ("book", "Без світла 1: рахуємо кадри"),
             ("edit", "Без світла 2: розкадровка"), ("chart", "Як оцінюємо")],
            notes="Домашнє завдання: придумати 5-секундну анімацію для своєї моделі з ПР 6 і записати ключові кадри таблицею.")

d.levels([("Обертання", "до 6 балів", ["Кінець = 72.", "Ключі на 1 і 72.", "Повний оберт навколо Z."]),
          ("Пульсація", "до 9 балів", ["Ключі масштабу 1–36–72.", "Рух «Лінійна» для обертання.",
                                                  "Збережено .blend."]),
          ("Свій ефект", "до 12 балів", ["Зміна кольору: ключ на Базовий колір.", "Або стрибок, поява, блимання.",
                                        "Рендер відео: Рендер → Рендер анімації."])],
         notes="Рівень 3: колір анімують так само — навести мишку на поле «Базовий колір» у вкладці «Матеріал» і натиснути I.")

s = d.task("Без світла 1: рахуємо кадри",
           "Відповіді: а) 48; б) 120; в) 2,5 с; г) ≈ 90°; д) ≈ 270°.\nБали: 5 правильних — 3; 3–4 — 2; 1–2 — 1.",
           where="У зошиті")
s.steps(["24 кадри = 1 секунда. Ключі: кадр 1 — <b>0°</b>, кадр 73 — <b>360°</b>, рух рівномірний."], w=1664, size=30)
for k, t in enumerate(["а) Скільки кадрів у 2 секундах?", "б) Скільки кадрів у 5 секундах?", "в) 60 кадрів — це скільки секунд?",
                       "г) Який кут на кадрі 19?", "д) Який кут на кадрі 55?"]):
    s.card(128, 300 + k * 120, 1100, 100, None, t, kind="light", body_size=30)
s.card(1280, 300, 512, 580, "Підказка", ["72 кадри — 360°.", "18 кадрів — 90°.", "Кадр 19: пройшло 18 кадрів."],
       kind="blue", title_size=34, body_size=30, valign="flex-start")

s = d.task("Без світла 2: розкадровка",
           "Зараховуємо: 4 кадри-малюнки з номерами; під кожним — що змінено (кут, розмір, колір); ключові кадри позначено ★.\n"
           "Бали: малюнки — 1, підписи — 1, правильні ключі — 1.", where="У зошиті")
s.steps(["Накресліть 4 прямокутники-кадри: <b>1, 24, 48, 72</b>.",
         "Намалюйте в них кулю, що <b>змінює колір</b>: червона → жовта → синя → червона.",
         "Під кожним кадром підпишіть колір. Позначте ★ ключові кадри.",
         "⭐ Додайте стрибок: на кадрі 36 куля найвище."], w=1100, size=30, gap=16)
