def art_block(art, w, h, squash=False, extra=""):
    par = "none" if squash else "xMidYMid slice"
    return (f'<div style="width:{w}px;height:{h}px;border:2px solid #3E3F42;border-radius:4px;overflow:hidden;'
            f'box-sizing:border-box;flex:none;{extra}"><svg width="100%" height="100%" viewBox="0 0 160 120" '
            f'preserveAspectRatio="{par}">{ART[art]}</svg></div>')


def doc_box(s, x, y, w, h, fname, inner, pad=28):
    """Аркуш документа зі смужкою назви файлу; вміст — звичайна HTML-верстка."""
    s.raw(f'<div style="position:absolute;left:{x}px;top:{y}px;width:{w}px;height:{h}px;background:#FBFCFD;'
          f'border:2px solid #3E3F42;border-radius:8px;box-sizing:border-box;overflow:hidden;'
          f'box-shadow:0 10px 30px rgba(30,40,60,0.18);color:{INK}">'
          f'<div style="background:#E6EAF0;border-bottom:2px solid #3E3F42;padding:8px 18px;font-size:20px;'
          f'font-weight:600;white-space:nowrap;overflow:hidden">{fname}</div>'
          f'<div style="padding:{pad}px {pad + 4}px;display:flex;flex-direction:column;gap:10px">{inner}</div></div>')


def patient(s, x, y, w, h, k=1.0):
    fs = int(20 * k)
    big = int(46 * k)
    inner = (f'<p style="font-family:\'Comic Sans MS\',cursive;color:#D9342B;font-size:{big}px;font-weight:700;line-height:1.1">ПОХІД!!!!!!</p>'
             f'<p style="font-family:\'Courier New\',monospace;font-size:{big}px;line-height:1.05">увага всім</p>'
             f'<p style="font-size:{fs}px;line-height:1.4">{RUN_ON}</p>'
             f'<p style="font-size:{fs}px;line-height:1.4">{WHO}</p>'
             + art_block("forest", int((w - 64)), int(95 * k), squash=True))
    doc_box(s, x, y, w, h, "Документ без назви (7) остаточний2.txt", inner, pad=int(26 * k))


def healthy(s, x, y, w, h, k=1.0):
    fs = int(19 * k)
    li = "".join(f'<p style="font-size:{fs}px;line-height:1.35">•&nbsp; {t}</p>' for t in THINGS)
    ol = "".join(f'<p style="font-size:{fs}px;line-height:1.35">{i}.&nbsp; {t}</p>' for i, t in enumerate(DAY, 1))
    cells = "".join(
        f'<div style="padding:{int(3 * k)}px {int(10 * k)}px;font-size:{fs}px;{"font-weight:700;background:#DCE4EE;" if r == 0 else ""}'
        f'border-right:{"0" if ci == 2 else "1.5px solid #3E3F42"};border-bottom:{"0" if r == 4 else "1.5px solid #3E3F42"}">{v}</div>'
        for r, row in enumerate(PEOPLE) for ci, v in enumerate(row))
    inner = (f'<p style="font-size:{int(34 * k)}px;font-weight:700;text-align:center;line-height:1.2">Похід до лісу</p>'
             f'<div style="display:flex;flex-direction:row;gap:{int(16 * k)}px;align-items:flex-start">'
             f'<div style="display:flex;flex-direction:column;gap:4px">{art_block("forest", int(170 * k), int(128 * k))}'
             f'<p style="font-size:{int(15 * k)}px;font-style:italic;color:{INK2}">Ліс біля села. Фото: pexels.com</p></div>'
             f'<div><p style="font-size:{fs}px;font-weight:700">Що взяти з собою</p>'
             f'{li}</div></div>'
             f'<div><p style="font-size:{fs}px;font-weight:700">Як пройде день</p>'
             f'{ol}</div>'
             f'<div><p style="font-size:{fs}px;font-weight:700;margin-bottom:6px">Учасники</p>'
             f'<div style="display:grid;grid-template-columns:auto auto auto;width:fit-content;border:1.5px solid #3E3F42;'
             f'border-radius:6px;overflow:hidden">{cells}</div></div>')
    doc_box(s, x, y, w, h, "Похід — Коваль.docx", inner, pad=int(24 * k))


def blur_start(s, px=6):
    s.raw(f'<div style="position:absolute;left:0px;top:0px;width:1920px;height:1080px;filter:blur({px}px)">')


def blur_end(s):
    s.raw('</div>')


