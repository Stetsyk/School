import os

from deck import REPO, c
import gdocs  # noqa: F401  — s.gshot, s.gsteps
import gdocs_shots as G
from vstavka import patch_deck

P5 = os.path.join(REPO, "Презентації уроків", "5 клас", "Урок І-11. Текстовий документ.html")
P6 = os.path.join(REPO, "Презентації уроків", "6 клас", "Урок І-07-08. Формати, списки й таблиці.html")


# ---------- 5 клас, І-11 ----------
def panel(d):
    s = d.slide("Де це на панелі Google Документів",
                "Показуємо на скріні по номерах. 1 — спершу виділяємо слово (воно стає блакитним). 2 — шрифт (Arial). "
                "3 — розмір: віконце між «−» і «+», можна вписати число. 4 — B жирний, I курсив, U підкреслений. "
                "5 — колір літер (буква A з рисочкою).\n"
                "Увага: у Google Документах на кнопках латинські B, I, U, а не Ж, К, П.\n"
                "Клавіші: Ctrl + B — жирний, Ctrl + I — курсив, Ctrl + U — підкреслений.\n"
                "Питаємо: «Натиснули B, а нічого не змінилось. Чому?» → нічого не було виділено.")
    s.h2("Де це на панелі Google Документів", size=64, top=104)
    s.gsteps_row(["<b>Виділіть</b> слово.", "<b>Шрифт</b>.", "<b>Розмір</b>.", "<b>B</b> · <b>I</b> · <b>U</b>.",
                  "<b>Колір</b> літер."], y=210, size=28)
    s.gshot(128, 330, 1180, G.format_toolbar(), maxh=640)
    s.table(1350, 330, [120, 322], [["Кнопка", "Що робить"], ["<b>B</b>", "жирний · Ctrl+B"],
                                   ["<i>I</i>", "курсив · Ctrl+I"], ["<u>U</u>", "підкреслений · Ctrl+U"]],
            row_h=78, size=26)


patch_deck(P5, after="Форматування: що можна змінити", build=panel,
           fixes=[("Ж жирний, К курсив, П підкреслений", "B жирний, I курсив, U підкреслений"),
                  ("тисну Ж і потім друкую", "тисну B і потім друкую")], replace=True)


# ---------- 6 клас, І-07-08 ----------
def lists(d):
    s = d.slide("Списки: дві кнопки на панелі",
                "Показуємо на скрінах по номерах. Спершу кожен пункт — окремим рядком (Enter після кожного). "
                "1 — виділяємо продукти, 2 — «Маркований список». 3 — виділяємо дії, 4 — «Нумерований список». "
                "Стрілочка біля кнопки відкриває вибір вигляду маркера чи номера.\n"
                "Клавіші: Ctrl + Shift + 8 — маркований, Ctrl + Shift + 7 — нумерований.\n"
                "Питаємо: «Збити яйця — це продукт чи дія?» → дія, у нумерований.")
    s.h2("Списки: дві кнопки на панелі", size=64, top=104)
    s.gsteps(["Виділіть <b>продукти</b> (кожен — окремим рядком).", "<b>Маркований список</b>."], x=128, y=220, w=800,
             size=29, gap=12)
    s.gshot(128, 360, 800, G.lists("bullet", ["два яйця", "склянка молока", "склянка борошна", "щіпка солі"]),
            maxh=620, align="center")
    s.gsteps(["Виділіть <b>дії</b>.", "<b>Нумерований список</b>."], x=992, y=220, w=800, size=29, gap=12, start=3)
    s.gshot(992, 360, 800, G.lists("number", ["Збити яйця з цукром", "Влити молоко", "Всипати борошно",
                                              "Смажити з обох боків"], nums=(3, 4)), maxh=620, align="center")


def table_insert(d):
    s = d.slide("Таблиця в Google Документах",
                "Показуємо на скріні по номерах: 1 — «Вставити», 2 — «Таблиця», 3 — обводимо мишкою сітку. "
                "Під сіткою Google пише розмір: спершу стовпці, потім рядки — «4 x 6».\n"
                "Типова хиба: шукають таблицю в меню «Формат». Там лише налаштування вже готової таблиці.\n"
                "Питаємо: «Під сіткою 6 x 4. Це те, що нам треба?» → ні: це 6 стовпців і 4 рядки.")
    s.h2("Таблиця в Google Документах", size=64, top=104)
    s.gsteps(["Меню <b>Вставити</b>.", "<b>Таблиця</b>.", "Обведіть сітку <b>4 x 6</b>: спершу стовпці, потім рядки."],
             x=128, y=230, w=440, size=30)
    s.gshot(610, 210, 1182, G.insert_table(4, 6, title="Таблиці — Прізвище", heading="Ярмарок"), maxh=830)


def table_fix(d):
    s = d.slide("Рядок і стовпець: права кнопка",
                "Показуємо на скрінах. Ліворуч: права кнопка по клітинці → «Вставити рядок нижче». Праворуч: права кнопка "
                "в потрібному стовпці → «Вставити стовпець справа». У тому ж меню — «Видалити рядок / стовпець / таблицю».\n"
                "Обережно: видалили рядок — зникли всі його дані. Повернути одразу: Ctrl + Z.")
    s.h2("Рядок і стовпець: права кнопка", size=64, top=104)
    s.gsteps(["<b>Правою</b> кнопкою — по клітинці.", "<b>Вставити рядок нижче</b>."], x=128, y=220, w=800, size=29,
             gap=12)
    s.gshot(128, 360, 800, G.table_row_below(), maxh=640, align="center")
    s.gsteps(["<b>Правою</b> кнопкою — у стовпці.", "<b>Вставити стовпець справа</b>."], x=992, y=220, w=800, size=29,
             gap=12, start=3)
    s.gshot(992, 360, 800, G.table_col_right(nums=(3, 4)), maxh=640, align="center")


def merge(d):
    s = d.slide("Об’єднати клітинки: як це зробити",
                "Показуємо на скріні по номерах. 1 — протягуємо мишкою по двох клітинках «Понеділок» (стають блакитними). "
                "2 — права кнопка по виділеному → «Об’єднати клітинки». Зайве друге слово «Понеділок» потім стираємо.\n"
                "Скасувати: права кнопка → «Скасувати об’єднання клітинок».\n"
                "Питаємо: «Можна об’єднати клітинки, що не стоять поруч?» → ні, лише сусідні.")
    s.h2("Об’єднати клітинки: як це зробити", size=64, top=104)
    s.gsteps(["Виділіть <b>сусідні</b> клітинки мишкою.", "Права кнопка → <b>Об’єднати клітинки</b>."], x=128, y=230,
             w=520, size=30)
    s.gshot(700, 210, 1092, G.merge_cells(), maxh=830)


fixes6 = [("Вставлення → Таблиця", "Вставити → Таблиця"), ("Google Документах: Вставлення, Таблиця", "Google Документах: Вставити, Таблиця"),
          ('color:#2F3033;">Вставлення</p>', 'color:#2F3033;">Вставити</p>'), ("Вставлення  →  Таблиця", "Вставити  →  Таблиця"),
          ("Вставити стовпець ліворуч", "Вставити стовпець зліва"), ("Вставити стовпець праворуч", "Вставити стовпець справа")]
patch_deck(P6, fixes=fixes6)
patch_deck(P6, after="Скільки яєць? Що робити третім?", build=lists, replace=True)
patch_deck(P6, after="Таблицю не малюють, а вставляють", build=table_insert, replace=True)
patch_deck(P6, after="Помилились із розміром? Нічого страшного", build=table_fix, replace=True)
patch_deck(P6, after="Об’єднання клітинок", build=merge, replace=True)
