s = d.task("Варіант В: свій сценарій",
           "Для сильних учнів. Сценарій — з домашнього завдання уроку ІІ-12.\nЗарахувати: ті самі вимоги; розкадровка в зошиті; "
           "оцінюємо задум, плавність і акуратність, а не складність.", where="За комп’ютером")
