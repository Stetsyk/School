    "Справжній скрін (з уроку ІІ-12). 1 — вкладка «Вивід». 2 — шлях: своя папка. 3 — «Формат файлу» → 4 — «Відео FFmpeg», "
    "контейнер MPEG-4. Потім Рендер → Рендер Анімації (Ctrl + F12).\n"
