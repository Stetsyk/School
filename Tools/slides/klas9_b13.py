"""9 клас, урок ІІ-13. Практична робота № 7. Створення 3D-анімації.
Варіанти: А — карусель (оберт через порожняк), Б — лампа вмикається (ключі «Сила Емісії»), В — свій сценарій.
Скріни — справжній Blender (ті самі, що в ІІ-11/ІІ-12): меню ключа I, вкладка «Вивід» → «Відео FFmpeg»."""
from deck import c
import klas9_3d as K
from kritakroky import how
from blenderkroky import bk

L = 13

CAROUSEL = '''
clean(cam=(9, -9, 5.5), target=(0, 0, 1.4))
add("cylinder", "Основа", loc=(0, 0, 0.15), scale=(2.2, 2.2, 0.15), color="#E6E8EC", vertices=64)
add("cylinder", "Стовп", loc=(0, 0, 1.6), scale=(0.12, 0.12, 1.4), color="#8C8F94", vertices=32)
add("cone", "Дах", loc=(0, 0, 3.3), scale=(2.4, 2.4, 0.6), color="#D9342B", vertices=64)
bpy.ops.object.empty_add(type="PLAIN_AXES", location=(0, 0, 0))
_e = bpy.context.active_object
_e.name = "Обертання каруселі"
_cols = ["#2F6FB7", "#F7CE46", "#4E8F4A", "#E8772E"]
for _i in range(4):
    _a = math.radians(90 * _i)
    _h = add("uv_sphere", "Кабінка %d" % (_i + 1), loc=(1.6 * math.cos(_a), 1.6 * math.sin(_a), 1.0),
             scale=(0.35, 0.35, 0.35), color=_cols[_i], segments=32, ring_count=16)
    bpy.context.view_layer.objects.active = _h
    bpy.ops.object.shade_smooth()
    _h.parent = _e
sc = bpy.context.scene
sc.frame_start, sc.frame_end = 1, 120
_e.rotation_euler = (0, 0, 0); _e.keyframe_insert("rotation_euler", frame=1)
_e.rotation_euler = (0, 0, math.radians(360)); _e.keyframe_insert("rotation_euler", frame=121)
for _fc in _e.animation_data.action.fcurves:
    for _k in _fc.keyframe_points:
        _k.interpolation = "LINEAR"
'''

LAMP_ON = K.LAMP + '''
_l = bpy.data.objects["Лампочка"]
_m = mat(_l, (1.0, 0.95, 0.75), "Лампочка світиться")
_bs = next(n for n in _m.node_tree.nodes if n.type == "BSDF_PRINCIPLED")
_bs.inputs["Emission Color"].default_value = (1.0, 0.85, 0.45, 1)
_es = _bs.inputs["Emission Strength"]
sc = bpy.context.scene
sc.frame_start, sc.frame_end = 1, 96
for _f, _v in [(1, 0.0), (36, 0.0), (48, 12.0), (96, 12.0)]:
    _es.default_value = _v
    _es.keyframe_insert("default_value", frame=_f)
'''

P_CAR = K.zrazok(L, "варіант А — карусель", CAROUSEL, anim=".mp4")
P_LAMP = K.zrazok(L, "варіант Б — лампа вмикається", LAMP_ON, anim=".mp4")

S = K.SPIN + 'select("Куб")\nbpy.context.scene.frame_set(36)\nview(rot=(64, 0, 35), dist=9, target=(0, 0, 1))\n'
IMENU = bk(S, ["mousemove 500 400", "key i", "sleep 0.8"], layout="row",
           parts=[(250, 150, 620, 500), (1132, 440, 1366, 625)],
           marks=[(262, 329, 560, 351, "right"), (264, 402, 554, 421, "right"), (1176, 464, 1306, 526, "left")])
SOUT = K.BOUNCE + 'select("М’яч")\nview(rot=(75, 0, 0), dist=13, target=(0, 0, 1.5))\n'
OUT = bk(SOUT, ["mousemove 1146 374", "click 1", "sleep 1.0", "mousemove 1240 500"] + ["click 5", "sleep 0.1"] * 12 +
         ["sleep 0.5", "mousemove 1300 525", "click 1", "sleep 0.8"],
         parts=[(862, 330, 1366, 740)],
         marks=[(1136, 364, 1158, 386, "left"), (1174, 440, 1350, 461, "top"), (1249, 515, 1350, 536, "top"),
                (1213, 616, 1330, 640, "bottom")])

d = K.deck(L, "", "")

s = d.title("ПР 7", "3D-анімація", "Практична робота № 7 · 9 клас", big_size=260, big_top=600,
            notes="Практична робота: кожен робить 4–5-секундну анімацію й рендерить її у відео MP4. Варіанти А і Б — з готовими "
                  "числами, В — власний сценарій (домашнє завдання з уроку ІІ-12).")
K.render_img(s, 1180, 150, 620, P_CAR)

d.plan(["Що здаємо", "Сценарій: розкадровка", "Пам’ятка: ключі", "Варіант А: карусель", "Варіант Б: лампа вмикається",
        "Варіант В: свій сценарій", "Відео MP4", "Як оцінюємо"],
       notes="Пояснення — до 8 хвилин. Рендер відео займає час: хай учні рендерять у 50 % розміру й Eevee.")

s = d.slide("Що здаємо",
            "Вимоги однакові для всіх варіантів.\nЗдаємо: «ПР7 — Прізвище.blend» і відео «ПР7 — Прізвище.mp4». "
            "Учитель відкриває .blend, дивиться таймлайн (ключі) і «Структуру», переглядає відео.\n"
            "Якщо відео не встигли — зараховуємо .blend з анімацією, але мінус бали за відео.")
s.h2("Що здаємо")
s.steps(["Анімація <b>4–5 секунд</b> (96–120 кадрів), <b>Кінець</b> налаштовано.",
         "Рухаються <b>хоча б 2 речі</b> (або одна річ і камера / світло).",
         "Ключі на правильних об’єктах; деталі не «відстають» (Ctrl + P).",
         "Об’єкти мають назви й матеріали.",
         "Відео: " + c("ПР7 — Прізвище.mp4") + " + файл " + c("ПР7 — Прізвище.blend") + "."], w=1100, size=31, gap=18)
K.render_img(s, 1290, 220, 502, P_LAMP, label="наприклад, лампа вмикається")

s = d.slide("Сценарій: розкадровка",
            "Справжні аніматори спершу малюють розкадровку: що відбувається на якій секунді.\n"
            "Питаємо: «Карусель робить повний оберт за 5 секунд. Скільки це кадрів?» → 120. «Лампа вмикається на 2-й секунді — "
            "кадр?» → 48.\nРозкадровку робимо в зошиті за 3 хвилини, потім — за комп’ютер.")
