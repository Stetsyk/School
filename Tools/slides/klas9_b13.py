s = d.task("Варіант Б: лампа вмикається",
           "Беремо лампу з ПР 6. Світіння — у матеріалі лампочки: розділ «Випромінювання», поле «Сила Емісії».\n"
           "Зарахувати: лампа з ПР 6; лампочка вимкнена 1,5 с, вмикається за пів секунди й світить; + ще один рух "
           "(абажур обертається або камера); відео.", where="За комп’ютером")
s.steps(["Відкрийте лампу з ПР 6. <b>Кінець</b> = " + c("96") + ".",
         "Лампочка → вкладка <b>Матеріал</b> → розділ <b>Випромінювання</b>: колір жовтий.",
         "<b>Сила Емісії</b>: кадр 1 і 36 — " + c("0") + ", кадр 48 — " + c("12") + " (мишка на поле → <b>I</b>).",
         "Ще один рух на вибір. Відео MP4."], w=1100, size=27, gap=10)
s.table(128, 600, [300, 180, 180, 180, 180], [["Кадр", "1", "36", "48", "96"], ["Сила Емісії", "0", "0", "12", "12"]],
        row_h=70, size=28)
