def plain_table(s, x, y, widths, rows, row_h=60, size=24, head_bold=False, fills=None, aligns=None,
                grid="#3E3F42"):
    """Таблиця, як вона виглядає в документі одразу після вставлення: білі клітинки, тонкі лінії."""
    cols = len(widths)
    aligns = aligns or ["left"] * cols
    fills = fills or {}
    cells = []
    for r, row in enumerate(rows):
        for ci, v in enumerate(row):
            bg = fills.get((r, ci), fills.get((r, None), "#FFFFFF"))
            fw = 700 if (head_bold and r == 0) else 400
            cells.append(f'<div style="height:{row_h}px;padding:0px 14px;display:flex;flex-direction:row;align-items:center;box-sizing:border-box;'
                         f'justify-content:{"flex-end" if aligns[ci] == "right" else ("center" if aligns[ci] == "center" else "flex-start")};'
                         f'font-size:{size}px;font-weight:{fw};color:{INK};background:{bg};white-space:nowrap;overflow:hidden;'
                         f'border-right:{"0" if ci == cols - 1 else "1.5px solid " + grid};'
                         f'border-bottom:{"0" if r == len(rows) - 1 else "1.5px solid " + grid}">{v}</div>')
    s.raw(f'<div style="position:absolute;left:{x}px;top:{y}px;display:grid;'
          f'grid-template-columns:{" ".join(str(w) + "px" for w in widths)};border:1.5px solid {grid}">'
          + "".join(cells) + "</div>")


