# Урок 28, рівень 3. Гра «Збирач зірок» — повний код.
# Стрілки рухають героя. Торкнувся зірки — +1 і зірка стрибає в нове місце.
# Покращення на вибір: межі полотна, «Перемога!» на 10 зірках, ворог, таймер.
import tkinter
import random

вікно = tkinter.Tk()
вікно.title("Збирач зірок")

полотно = tkinter.Canvas(вікно, width=600, height=400, bg="#EAF2FF")
полотно.pack()

рахунок = 0
табло = полотно.create_text(80, 25, text="Зірок: 0", font=("Arial", 18))
герой = полотно.create_rectangle(270, 320, 320, 370, fill="orange")
зірка = полотно.create_oval(400, 100, 440, 140, fill="gold", outline="orange", width=3)


def перевірити():
    global рахунок
    г = полотно.coords(герой)
    поруч = полотно.find_overlapping(г[0], г[1], г[2], г[3])
    if зірка in поруч:
        рахунок += 1
        полотно.itemconfig(табло, text=f"Зірок: {рахунок}")
        x = random.randint(20, 550)
        y = random.randint(50, 350)
        полотно.coords(зірка, x, y, x + 40, y + 40)


def ліворуч(подія):
    полотно.move(герой, -20, 0)
    перевірити()


def праворуч(подія):
    полотно.move(герой, 20, 0)
    перевірити()


def вгору(подія):
    полотно.move(герой, 0, -20)
    перевірити()


def вниз(подія):
    полотно.move(герой, 0, 20)
    перевірити()


полотно.bind("<Left>", ліворуч)
полотно.bind("<Right>", праворуч)
полотно.bind("<Up>", вгору)
полотно.bind("<Down>", вниз)
полотно.focus_set()

вікно.mainloop()
