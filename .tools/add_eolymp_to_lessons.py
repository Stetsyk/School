def titles():
    t = {}
    for f in glob.glob(os.path.join(DUMP, "*.md")):
        s = open(f, encoding="utf-8").read(400)
        n = re.search(r"^number: (\d+)", s, re.M)
        ti = re.search(r'^title: "(.*)"', s, re.M)
        dl = re.search(r'^difficulty_label: "(.*)"', s, re.M)
        if n:
            t[int(n.group(1))] = (ti.group(1) if ti else "?", dl.group(1) if dl else "—")
    return t


def block(num, T):
    main, bonus, intro, note = DATA[num]

    def lines(items):
        out = []
        for n, what in items:
            what = DESC_FIX.get(n, what)
            title, diff = T.get(n, ("?", "—"))
            out.append(f"- **{n}** · [{title}](https://eolymp.com/uk/problems/{n}) — {what}"
                       + (f" _({diff.lower()})_" if diff not in ("Дуже легка", "—") else ""))
        return "\n".join(out)

    p = ["", "---", "", "## 8. 🏆 Задачі на e-olymp", "",
         "> Шукати за номером: `eolymp.com/uk/problems/НОМЕР`", "", intro, "", "**Основні:**", "",
         lines(main), "", "**⭐ Для сильніших:**", "", lines(bonus), ""]
    if num in TWO_STAR:
        p += ["**⭐⭐ Якщо і цього мало:**", "", lines(TWO_STAR[num]), ""]
    if note:
        p += [note, ""]
    return "\n".join(p)


def main():
    T = titles()
    files = sorted(glob.glob(os.path.join(LESSONS, "Урок *.md")))
    changed = 0
    for f in files:
        num = int(re.search(r"Урок (\d+)", os.path.basename(f)).group(1))
        if num not in DATA:
            print("пропущено:", os.path.basename(f)); continue
        s = open(f, encoding="utf-8").read()
        s = re.split(r"\n+---\n+## 8\. 🏆 Задачі на e-olymp", s)[0].rstrip()
        open(f, "w", encoding="utf-8").write(s + "\n" + block(num, T))
        changed += 1
    print(f"оновлено уроків: {changed}")


if __name__ == "__main__":
    main()
